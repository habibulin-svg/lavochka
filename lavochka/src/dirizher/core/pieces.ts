export type DiffName = 'learn' | 'easy' | 'normal' | 'hard' | 'master';

export interface Concert {
  id: string;
  /** Афиша. */
  title: string;
  pieces: string[];
  diff: DiffName;
  /** Гонорар за звезду. */
  fee: number;
}

export interface Hall {
  id: string;
  name: string;
  city: string;
  /** Время реверберации, с. */
  rt60: number;
  /** Мест в зале (для подписи). */
  seats: number;
  about: string;
  concerts: Concert[];
}

export interface Season {
  id: string;
  title: string;
  halls: Hall[];
}

