const tplOf = (id: string) => TPL.find((t) => t.id === id)!;

export const solveZadachka = (d: ZadachkaData) => tplOf(d.id).ans(d.p);

export function genZadachka(level: number, names: string[], rng: Rng): { data: ZadachkaData; sol: number } {
  const pool = TPL.filter((t) => t.level === level);
  const t = pool[rng.int(pool.length)];
  const p = t.params(rng);
  const k = rng.int(names.length);
  const nm = (i: number) => names[(k + i) % names.length];
  const z = t.text(p, nm(0), nm(1), nm(2));
  return { data: { id: t.id, p, ...z }, sol: t.ans(p) };
}
