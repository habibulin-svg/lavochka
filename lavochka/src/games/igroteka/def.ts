const at = (g: GameId, r: number, c: number) => geo(BOARD_OF[g]).at(r, c);

function describe(ev: Event, name: (seat: number) => string): string | null {
  if (ev.type === 'move' && ev.caps.length) return `${name(ev.seat)}: снято ${ev.caps.length === 1 ? 'фишку' : `${ev.caps.length} фишки`}.`;
  if (ev.type === 'move' && ev.king) return `${name(ev.seat)}: шашка стала дамкой.`;
  if (ev.type === 'take') return `${name(ev.seat)}: три в ряд — снята фишка соперника.`;
  if (ev.type === 'out') return `${name(ev.seat)}: шашка дошла до последнего ряда и снята.`;
  if (ev.type === 'huff') return `${name(ev.seat)}: бросил цепочку прыжков — фишка снята.`;
  if (ev.type === 'pass') return `${name(ev.seat)} пропускает ход.`;
  if (ev.type === 'end') {
    if (ev.winner == null) return ev.why === 'repeat' ? '🏁 Ходы повторяются — ничья.' : ev.why === 'apart' || ev.why === 'count' ? '🏁 Поровну — ничья.' : '🏁 Ничья.';
    const why: Record<string, string> = {
      broke: 'прорвался',
      trapped: 'сопернику некуда ходить',
      line: 'ряд собран',
      eaten: 'съедено достаточно',
      few: 'у соперника две фишки',
      all: 'сняты все фишки соперника',
      apart: 'шашки разошлись — у победителя их больше',
      count: 'снято больше фишек',
      checkers: 'шашки соперника кончились или заперты',
    };
    return `🏁 Победа: ${name(ev.winner)} — ${why[ev.why] ?? 'партия окончена'}${ev.points ? ` (${ev.points} очк.)` : ''}.`;
  }
  return null;
}

const demoSeats: SeatSpec[] = [0, 1].map((seat) => ({ seat, kind: 'bot', name: SEATS[seat].name, level: 1 }));

/** Позиция для показа: фишки мест 0 и 1 по условным координатам. */
function pos(g: GameId, w: [number, number][], b: [number, number][], o: Partial<State> = {}, opts: Record<string, any> = {}): State {
  const s = newState(cfgFrom({ game: g, ...opts }));
  s.board.fill(0);
  for (const [r, c] of w) s.board[at(g, r, c)] = 1;
  for (const [r, c] of b) s.board[at(g, r, c)] = 2;
  s.hand = [0, 0];
  s.ply = 1;
  return { ...s, ...o };
}
const Pl = (g: GameId, seat: number, r: number, c: number, caption?: string): DemoStep<Action> => ({ seat, action: { type: 'place', to: at(g, r, c) }, caption });
const Mv = (g: GameId, seat: number, a: [number, number], b: [number, number], caption?: string): DemoStep<Action> => ({ seat, action: { type: 'move', from: at(g, a[0], a[1]), to: at(g, b[0], b[1]) }, caption });
const Tk = (g: GameId, seat: number, r: number, c: number, caption?: string): DemoStep<Action> => ({ seat, action: { type: 'take', at: at(g, r, c) }, caption });

function fixedRng(seed: number): Rng {
  let x = seed;
  return {
    next: () => (x = (x * 1103515245 + 12345) % 2147483648) / 2147483648,
    int(n: number) {
      return Math.floor(this.next() * n);
    },
    getState: () => x,
  };
}

