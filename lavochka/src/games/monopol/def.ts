const fmt = (n: number) => n.toLocaleString('ru-RU');

function describe(ev: Event, name: (seat: number) => string): string | null {
  switch (ev.type) {
    case 'buy':
      return ev.from != null ? `${name(ev.seat)} перекупает «${cellAt(ev.loc).name}» у ${name(ev.from)} за ${fmt(ev.price)}.` : `${name(ev.seat)} покупает «${cellAt(ev.loc).name}» за ${fmt(ev.price)}.`;
    case 'rent':
      return `${name(ev.seat)} платит ${name(ev.owner)} ${fmt(ev.amount)} за «${cellAt(ev.loc).name}».`;
    case 'loan':
      return `${name(ev.seat)} берёт кредит ${fmt(ev.amount)} на ${ev.bank === 0 ? 'Папиной' : 'Маминой'} сберкнижке.`;
    case 'lottery':
      return `Лотерея «Спринт», ${ev.a}—${ev.b}: ${ev.text}.`;
    case 'bet':
      return `${name(ev.seat)}: рулетка, ${fmt(ev.amount)} на ${ev.num}, выпало ${ev.die} — ${ev.win ? `выигрыш ${fmt(ev.amount * 5)}!` : 'мимо'}.`;
    case 'pot':
      return `${name(ev.seat)} выбрасывает шестёрку в зале и забирает кассу игровых автоматов: ${fmt(ev.amount)}!`;
    case 'skip':
      return `${name(ev.seat)} пропускает ход.`;
    case 'broke':
      return `💸 ${name(ev.seat)} разорился.`;
    case 'invest':
      return ev.amount > 0 ? `${name(ev.seat)} вкладывает ${fmt(ev.amount)} в «${cellAt(ev.loc).name}».` : null;
    case 'money':
      if (ev.why === '+500' || Math.abs(ev.delta) < 1) return null;
      return `${name(ev.seat)}: ${ev.delta > 0 ? '+' : '−'}${fmt(Math.abs(ev.delta))} — ${ev.why}.`;
    case 'end':
      return ev.winner == null ? '🏁 Партия окончена — поровну.' : `🏁 Победа: ${name(ev.winner)} — состояние ${fmt(ev.worth[ev.winner])}.`;
  }
  return null;
}

const demoSeats: SeatSpec[] = [0, 1].map((seat) => ({ seat, kind: 'bot', name: SEATS[seat].name, level: 1 }));
/** Позиция для показа: двое, место 0 ходит. */
function pos(o: (s: State) => void): State {
  const s = newState(cfgFrom({}), 2);
  o(s);
  return s;
}
/** Бросок и перестановка пуговицы — два шага: фишку игрок ставит сам; подпись — когда пуговица встала (more — подкрутка для клетки). */
const Roll = (seat: number, die: number, caption?: string, more: number[] = []): DemoStep<Action>[] => [
  { seat, action: { type: 'roll' }, rig: [die - 1], caption: `Выпало ${die}…` },
  { seat, action: { type: 'move' }, rig: more, caption },
];
const Do = (seat: number, action: Action, caption?: string, rig?: number[]): DemoStep<Action> => ({ seat, action, caption, rig });

function fixedRng(seed: number): Rng {
  let x = seed;
  return {
    next: () => (x = (x * 1103515245 + 12345) % 2147483648) / 2147483648,
    int(n: number) {
      return Math.floor(this.next() * n);
    },
    getState: () => x,
  };
}

