const hole = (h: number) => (h === SHEN ? 'шен' : String(h));

function describe(ev: Event, name: (seat: number) => string): string | null {
  if (ev.type === 'roll') return `🥢 ${name(ev.seat)}: ${ev.value}${ev.none ? ' — ходить нечем' : ''}.`;
  if (ev.type === 'move') {
    const parts = [`${name(ev.seat)}: ${ev.from ? ev.from : 'новая фишка'} → ${hole(ev.land)}`];
    if (ev.to !== ev.land) parts.push(ev.to > ev.land ? `по змейке вперёд на ${ev.to}` : `по змейке назад на ${ev.to}`);
    if (ev.land === SHEN) parts.push(ev.took == null ? 'фишка вошла в шен' : 'вошла в шен и сняла отстающую фишку соперника');
    if (ev.again) parts.push('«нефер» — ещё бросок');
    return parts.join(', ') + '.';
  }
  if (ev.type === 'enter') return `${name(ev.seat)}: новая фишка вышла под пальму.`;
  if (ev.type === 'end') {
    if (ev.winner == null) return '🏁 Ничья.';
    const why = ev.why === 'out' ? 'у соперника не осталось фишек' : ev.why === 'shen' ? 'все фишки в шене' : 'по счёту';
    return `🏁 Победа: ${name(ev.winner)} — ${why}.`;
  }
  return null;
}

const demoSeats: SeatSpec[] = [0, 1].map((seat) => ({ seat, kind: 'bot', name: SEATS[seat].name, level: 1 }));

/** Позиция для показа: лунки собак и шакалов, фишек в руке; ходит место 0, ждёт броска. */
function pos(a: number[], b: number[], hand: [number, number] = [5 - a.length, 5 - b.length], opts: Options = {}): State {
  const s = newState(cfgFrom(opts), 0);
  s.pegs = [a.slice().sort((x, y) => x - y), b.slice().sort((x, y) => x - y)];
  s.hand = hand;
  return s;
}
/** Бросок палочек на value очков (5 — все тёмной стороной). */
const R = (seat: number, value: number, caption?: string): DemoStep<Action> => ({
  seat,
  action: { type: 'roll' },
  rig: [0, 1, 2, 3].map((i) => (value < 5 && i < value ? 1 : 0)),
  caption,
});
const Mv = (seat: number, from: number, caption?: string): DemoStep<Action> => ({ seat, action: { type: 'move', from }, caption });

function fixedRng(seed: number): Rng {
  let x = seed;
  return {
    next: () => (x = (x * 1103515245 + 12345) % 2147483648) / 2147483648,
    int(n: number) {
      return Math.floor(this.next() * n);
    },
    getState: () => x,
  };
}

