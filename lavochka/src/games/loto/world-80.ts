export const ED80_SHEETS: number[][] = Array.from({ length: 20 }, (_, i) => Array.from({ length: 6 }, (_, j) => i * 6 + j + 1));

/** Собрать тексты 1980 года из текстов 1972-го. */
export function build80(a72: Record<number, string>, q72: Record<number, string>) {
  const a: Record<number, string> = {};
  const q: Record<number, string> = {};
  for (let n = 1; n <= 120; n++) {
    const nw = NEW_80[n];
    if (nw) {
      a[n] = nw.a;
      q[n] = nw.q;
      continue;
    }
    const k = SAME_AS_72[n] ?? n;
    a[n] = a72[k];
    q[n] = q72[k];
  }
  return { a, q };
}
