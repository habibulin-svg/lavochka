/** Клетка по имени разметки: «T1»…«T4», «B1»…«B4», «d12», «bA» (для показа правил и тестов). */
export const cellOf = (name: string): number => {
  const got = ID.get(name);
  if (got == null) throw new Error(`нет клетки ${name}`);
  return got;
};

/** Соседи по дорогам: клетка → [соседняя клетка, номер дороги]. */
export const LINKS: [number, number][][] = Array.from({ length: N }, () => []);
ROADS.forEach((road, ri) => {
  for (let i = 0; i + 1 < road.length; i++) {
    LINKS[road[i]].push([road[i + 1], ri]);
    LINKS[road[i + 1]].push([road[i], ri]);
  }
});
/** Перекрёстки — клетки двух дорог. */
export const CROSS = new Set(LINKS.map((l, p) => (new Set(l.map((x) => x[1])).size > 1 ? p : -1)).filter((p) => p >= 0));
