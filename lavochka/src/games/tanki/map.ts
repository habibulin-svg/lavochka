/** Клетки: [x, y]. Номера 0…3 — верхние старты, 4…7 — нижние, дальше — точки дорог. */
export const XY: [number, number][] = [];
const ID = new Map<string, number>();
function c(name: string, x: number, y: number): number {
  const got = ID.get(name);
  if (got != null) return got;
  XY.push([x, y]);
  ID.set(name, XY.length - 1);
  return XY.length - 1;
}

