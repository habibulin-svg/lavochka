/* «Менеджер» и «Космос 2000» — поля и колоды, снятые с print'n'play-сканов printgames.ru (materials/manager, materials/kosmos2000).
 * Без DOM. Поле — кольцо клеток по ходу фишки; у каждой клетки прямоугольник на картинке в долях стороны (для отрисовки). */

export type Kind = 'start' | 'prop' | 'card' | 'money' | 'jail' | 'gojail' | 'rest' | 'casino' | 'hole' | 'pirates' | 'police' | 'insure';

export interface Cell {
  kind: Kind;
  name: string;
  /** Подпись в правилах и журнале (с кавычками и родом: «ресторан „Север“»). */
  full?: string;
  /** Участок/планета: цена. */
  price?: number;
  /** Плата за наём: пустой участок, 1–3 филиала, предприятие («Космос» — одна цифра). */
  rents?: number[];
  /** Цена филиала/предприятия. */
  build?: number;
  group?: number;
  /** Клетка карточки: какая колода. */
  deck?: number;
  /** Выигрыш/штраф: + получает, − платит. */
  amount?: number;
  /** Прямоугольник на поле (доли стороны) и сторона поля, к которой клетка прилегает. */
  x: number;
  y: number;
  w: number;
  h: number;
  side: 'b' | 'l' | 't' | 'r' | 'c';
}

export type Fx =
  | { k: 'cash'; n: number }
  | { k: 'goto'; to: number; back?: boolean; free?: boolean }
  | { k: 'step'; n: number }
  | { k: 'jail' }
  | { k: 'free' }
  | { k: 'repair'; h: number; e: number }
  | { k: 'draw'; deck: number }
  | { k: 'nearest'; kind: Kind; deck?: number; bonus?: number; insure?: boolean }
  | { k: 'pot'; n: number | null }
  | { k: 'birthday'; n: number }
  | { k: 'skip' }
  | { k: 'again' }
  | { k: 'police'; n: number };

export interface Card {
  text: string;
  fx: Fx;
}

export interface Group {
  name: string;
  color: string;
}

export interface Board {
  id: 'manager' | 'kosmos';
  title: string;
  img: string;
  cells: Cell[];
  groups: Group[];
  decks: { name: string; back: string; face?: string; cards: Card[] }[];
  /** Знак валюты в журнале. */
  cur: string;
  /** Самая мелкая купюра — шаг торгов. */
  step: number;
  /** Купюры для пачки денег (по убыванию). */
  notes: { v: number; img: string }[];
  /** Сколько дают на старте и за «Старт». */
  money(n: number): number;
  startPay: number;
  /** Куда сажают «на биржу» (только «Менеджер»). */
  jail: number;
}

/** Кольцо клеток по часовой стрелке на экране: угол c (доля стороны), n клеток на стороне; первая клетка — угол start (0 — левый нижний, 1 — левый верхний, 2 — правый верхний, 3 — правый нижний). */
function ring(c: number, n: number, start: number): Pick<Cell, 'x' | 'y' | 'w' | 'h' | 'side'>[] {
  const s = (1 - 2 * c) / n;
  const corners = [
    { x: 0, y: 1 - c },
    { x: 0, y: 0 },
    { x: 1 - c, y: 0 },
    { x: 1 - c, y: 1 - c },
  ];
  const out: Pick<Cell, 'x' | 'y' | 'w' | 'h' | 'side'>[] = [];
  for (let k = 0; k < 4; k++) {
    const ci = (start + k) % 4;
    out.push({ ...corners[ci], w: c, h: c, side: 'c' });
    for (let j = 1; j <= n; j++) {
      if (ci === 0) out.push({ x: 0, y: 1 - c - j * s, w: c, h: s, side: 'l' });
      else if (ci === 1) out.push({ x: c + (j - 1) * s, y: 0, w: s, h: c, side: 't' });
      else if (ci === 2) out.push({ x: 1 - c, y: c + (j - 1) * s, w: c, h: s, side: 'r' });
      else out.push({ x: 1 - c - j * s, y: 1 - c, w: s, h: c, side: 'b' });
    }
  }
  return out;
}

type Raw = Omit<Cell, 'x' | 'y' | 'w' | 'h' | 'side'>;
const place = (raw: Raw[], geo: ReturnType<typeof ring>): Cell[] => raw.map((r, i) => ({ ...r, ...geo[i] }));

