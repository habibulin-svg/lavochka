const STUFF: Record<Stuff, string> = { gold: 'кг золота', auto: 'автомобилей', cola: 'бочек колы', oil: 'баррелей нефти', drugs: 'т наркотика', trinkets: 'безделушек' };
const QUIET = new Set(['колония: клетка', 'покупка']);

export function describe(ev: Event, name: (seat: number) => string): string | null {
  switch (ev.type) {
    case 'roll':
      return `${name(ev.seat)} бросает${ev.back ? ' (назад)' : ''}: <b>${ev.d}</b>`;
    case 'cell': {
      const c = CELLS[ev.cell];
      return `${name(ev.seat)} — <b>${ev.cell}. ${c.name}</b>: <i>${c.text}</i>`;
    }
    case 'pay':
      if (QUIET.has(ev.why)) return null;
      if (ev.from == null) return `${name(ev.to!)} получает ${money(ev.amount)} — ${ev.why}`;
      return `${name(ev.from)} платит ${money(ev.amount)} ${ev.to == null ? 'банку' : name(ev.to)} — ${ev.why}`;
    case 'gold':
      return `${name(ev.seat)}: ${ev.kg > 0 ? '+' : '−'}${Math.abs(ev.kg)} кг золота — ${ev.why}`;
    case 'stuff':
      if (ev.why === 'покупка' && ev.what !== 'auto' && ev.what !== 'cola') return null;
      if (ev.n < 0) return null;
      return `${name(ev.seat)}: +${ev.n} ${STUFF[ev.what]} — ${ev.why}`;
    case 'lap':
      return `🏁 ${name(ev.seat)} закрывает ${ev.circle}-й круг: ${ev.lost ? `доход ${money(ev.income)} остаётся в банке` : `доход и дивиденды ${money(ev.income)}`}`;
    case 'labour':
      return `${name(ev.seat)}: индекс на бирже труда ${ev.labour > 0 ? '+' : ''}${ev.labour}`;
    case 'stock':
      return `📈 Курс ${CO[ev.cell].name}: ${ev.pts > 0 ? '+' : ''}${ev.pts} п.`;
    case 'price': {
      const g = GOODS[ev.good];
      return `📦 Товарная биржа: ${g.name} — ${money(g.nom + ev.pts * g.step)}`;
    }
    case 'buy':
      return ev.from != null
        ? `🤝 ${name(ev.seat)} покупает у ${name(ev.from)} ${CO[ev.cell].name} за ${money(ev.price)}`
        : `${name(ev.seat)} покупает ${CO[ev.cell].name} за ${money(ev.price)}`;
    case 'sell':
      return `${name(ev.seat)} продаёт ${CO[ev.cell].name} за ${money(ev.price)} — ${ev.why}`;
    case 'skip':
      return `${name(ev.seat)} пропускает ход${ev.left ? ` (ещё ${ev.left})` : ''}`;
    case 'jail':
      return ev.bribed ? `${name(ev.seat)}: полиция подкуплена — тюрьмы нет` : `⛓ ${name(ev.seat)}: пропуск ${ev.n} ${ev.n < 5 ? 'хода' : 'ходов'}`;
    case 'choice':
      return `${name(ev.seat)}: ${ev.label}`;
    case 'casino':
      return `🎲 ${name(ev.seat)} в казино ставит ${money(ev.bet)}: ${ev.d}${ev.win ? ' — вдесятеро!' : ' — ставка пропала'}`;
    case 'auction':
      if (ev.seat == null) return ev.bid ? `🔨 Торги: ${CO[ev.cell].name}, с ${money(ev.bid)}` : `🔨 Торги не состоялись`;
      return `🔨 ${name(ev.seat)}: ${money(ev.bid)}`;
    case 'bankrupt':
      return `💀 ${name(ev.seat)} — банкрот и выбывает`;
    case 'end':
      return `🏆 ${ev.winners.map(name).join(', ')} — ${ev.text}`;
  }
  return null;
}

