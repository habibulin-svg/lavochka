const demoSeats: SeatSpec[] = [0, 1].map((seat) => ({ seat, kind: 'bot', name: SEATS[seat].name, level: 1 }));

function demo(patch: (s: State) => void, steps: DemoScript<State, Action>['steps']): DemoScript<State, Action> {
  return {
    seats: demoSeats,
    options: { circles: 5, simple: false },
    setup: () => {
      const s = newState([0, 1], 5, false);
      patch(s);
      return s;
    },
    steps,
  };
}

/** Бросок и перестановка фишки — два шага (фишку ставит сам игрок); подпись — когда фишка встала. stay — развилка прямо на месте. */
const roll = (seat: number, d: number, caption: string, stay = false) =>
  stay
    ? [{ seat, action: { type: 'roll' } as Action, rig: [d - 1], caption }]
    : [
        { seat, action: { type: 'roll' } as Action, rig: [d - 1], caption: `Выпало ${d}…` },
        { seat, action: { type: 'move' } as Action, caption },
      ];
const move = (seat: number, caption: string) => ({ seat, action: { type: 'move' } as Action, caption });
const pick = (seat: number, id: string, caption: string, rig?: number[]) => ({ seat, action: { type: 'choose', id } as Action, caption, ...(rig ? { rig } : {}) });

