function describe(ev: Event, name: (seat: number) => string): string | null {
  switch (ev.type) {
    case 'start':
      return ev.variant === '960' ? `Фишер 960: позиция № ${ev.sp}.` : null;
    case 'move':
      return `${ev.seat === 0 ? `${ev.num}.` : `${ev.num}…`} <b>${ev.san}</b>${ev.check && !ev.san.endsWith('#') ? ' — шах!' : ''}`;
    case 'offer':
      return `${name(ev.seat)} предлагает ничью.`;
    case 'decline':
      return `${name(ev.seat)} отказывается от ничьей.`;
    case 'end':
      if (ev.winner == null) return `🤝 <b>${REASON[ev.reason]}</b>.`;
      return `🏆 <b>${name(ev.winner)}</b>: ${ev.reason === 'mate' ? 'мат!' : REASON[ev.reason]}.`;
  }
  return null;
}

