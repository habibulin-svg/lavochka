/* Таврели — разделы правил с показом (подмешиваются в правила карточки «Шахматы»). Без DOM. */
import type { SeatSpec } from '../../../core/types';
import { cfgFrom } from '../engine';
import { fromList, newTGame, sq, type TAction } from './engine';

const seats: SeatSpec[] = [
  { seat: 0, kind: 'bot', name: 'Белые', level: 1 },
  { seat: 1, kind: 'bot', name: 'Чёрные', level: 1 },
];
const cfg = () => cfgFrom({ variant: 'tavreli' });

/** Ход для показа: mv(0, 'e2', 'e4') — вся башня; n — сколько верхних таврелей отделить. */
const mv = (seat: number, from: string, to: string, caption?: string, n?: number) => ({
  seat,
  action: { type: 'move', from: sq(from), to: sq(to), n } as TAction,
  caption,
});

const demo = (intro: string, steps: ReturnType<typeof mv>[], list?: Record<string, string>, turn: 0 | 1 = 0) => ({
  seats,
  options: { variant: 'tavreli' },
  setup: () => (list ? fromList(list, cfg(), turn) : newTGame(cfg())),
  intro,
  steps,
});

