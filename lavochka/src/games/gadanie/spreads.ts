/* Расклады гадания: где лежит каждая карта и что значит её место. Без DOM — их читают стол, справочник, пререндер и сервер (Светка).
 * Место — в клетках стола: x, y — центр карты (единица — ширина карты с промежутком), rot — карта лежит поперёк (90°).
 * Классические — с источником (Уэйт 1910); остальные — народные и современные расклады, позиции и описания свои. */

export type DeckKind = 'taro' | 'karty';

export interface Spot {
  x: number;
  y: number;
  /** Карта поперёк (вторая карта кельтского креста). */
  rot?: boolean;
  /** Что значит место: «Что было», «Что мешает». */
  label: string;
  /** Подробнее — для справки и для Светки. */
  hint: string;
  /** Карт на месте (народные расклады на 36: «на сердце» — две карты). */
  n?: number;
}

export interface Spread {
  id: string;
  deck: DeckKind;
  title: string;
  /** Одна строка в списке. */
  sub: string;
  /** Как раскладывают и как читают (HTML-абзацы, свои слова). */
  about: string;
  spots: Spot[];
  /** Откуда расклад: «А. Э. Уэйт, 1910». */
  source?: string;
  /** Особый итог: «да/нет» по картам, «сбудется ли желание». */
  verdict?: 'yesno' | 'wish';
  /** На кого гадают: сначала выбрать короля или даму (карта лежит в середине открытой). */
  person?: boolean;
  /** Раздел в списке. */
  group: string;
}

const row = (labels: [string, string][], y = 0): Spot[] => labels.map(([label, hint], i) => ({ x: i - (labels.length - 1) / 2, y, label, hint }));

