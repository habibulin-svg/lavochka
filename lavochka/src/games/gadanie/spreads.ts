export const spreadById = (id: string) => SPREADS.find((s) => s.id === id);
export const spreadsOf = (deck: DeckKind) => SPREADS.filter((s) => s.deck === deck);
/** Сколько карт тянуть. */
export const spreadSize = (s: Spread) => s.spots.reduce((n, p) => n + (p.n ?? 1), 0);
