/* Покер — стили ботов. Стиль закреплён за именем (местом в SEATS): Вовка за любым столом играет одинаково, поэтому
 * статистика HUD по нему копится и становится полезной, как по живому регуляру. Уровень (Лёгкий/Средний/Сложный) —
 * сила внутри стиля: сложный точнее считает и реже ошибается, но стиль у него тот же.
 *
 * Целевые цифры — для стола на 6 игроков (холдем, безлимит, глубокие стеки); тест poker-bots меряет их по HandRecord.
 *   vpip — % раздач, где игрок добровольно вложил фишки до флопа; pfr — % раздач с рейзом до флопа;
 *   threeBet — % ре-рейза, когда перед ним был один рейз; af — (ставки + рейзы) / коллы после флопа;
 *   cbet — % продолженной ставки на флопе после своего рейза до флопа. */

export type ProfileId = 'tag' | 'lag' | 'nit' | 'station' | 'maniac' | 'fish';

export interface Profile {
  id: ProfileId;
  name: string;
  /** Коротко — для подсказки и HUD. */
  about: string;
  target: { vpip: [number, number]; pfr: [number, number]; threeBet: [number, number]; af: [number, number]; cbet: [number, number] };
  /** Ширина открытия рейзом — множитель к базовой таблице по позиции. */
  open: number;
  /** Доля открытий лимпом вместо рейза. */
  limp: number;
  /** Колл рейза: доля рук (в долях от всех), с которыми игрок продолжает против одного рейза (без 3-бета). */
  flat: number;
  /** Ширина 3-бета на вэлью (доля рук) и доля блефовых 3-бетов из рук сразу за коллом. */
  three: number;
  bluff3: number;
  /** После флопа: склонность ставить и повышать (1 — обычная), доля блефов, продолженная ставка. */
  aggr: number;
  bluff: number;
  cbet: number;
  /** «Липкость»: насколько ниже шансов банка игрок ещё коллирует (0.1 = на 10 п. п. хуже нужного). */
  stick: number;
  /** Пуш/фолд: множитель к стеку из таблиц Нэша (больше 1 — идёт ва-банк шире). */
  shove: number;
}

