/* «Бородино» — части и командующие (по листу фишек и таблице расстановки правил игры). Сила и движение: лицо — боевое состояние,
 * оборот — деморализованное; у артиллерии лицо — «к бою» (не двигается), оборот — «на колёсах» (сила в скобках — только для обороны).
 * Номера клеток — как на карте (ССРР). Пары «IV-1»/«IV-3» на листе дублируют прикреплённые к IV корпусу дивизии I-1 и I-3 — взяты одни. */

export type Kind = 'inf' | 'cav' | 'art' | 'cmd';
/** Национальность — порог приведения в боевое состояние: русские 2+, французы 3+, итальянцы, поляки и немцы 4+. */
export type Nat = 'ru' | 'fr' | 'xx';

export interface UnitDef {
  id: string;
  name: string;
  side: 0 | 1;
  kind: Kind;
  nat: Nat;
  /** Корпус (подпись на фишке). */
  corps: string;
  str: number;
  mp: number;
  str2: number;
  mp2: number;
  /** Клетка в начале (ССРР). */
  at: string;
  /** Командующий: рейтинг — str, корпуса под командой — cmds. */
  cmds?: string[];
}

