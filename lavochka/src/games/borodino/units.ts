/** Может ли командующий cmd вести в бой часть u. */
export function commands(cmd: UnitDef, u: UnitDef): boolean {
  if (!cmd.cmds || cmd.side !== u.side || u.kind === 'cmd') return false;
  return u.corps.split('+').some((c) => cmd.cmds!.includes(c)) || cmd.cmds.includes(u.corps);
}

