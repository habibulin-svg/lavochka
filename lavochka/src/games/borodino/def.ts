const nm = (i: number) => U[i].name;
const hx = (h: number) => (h >= 0 ? label(h) : '—');

function describe(ev: Event, name: (seat: number) => string): string | null {
  switch (ev.type) {
    case 'phase':
      if (ev.phase === 'deploy') return `Расстановка: ${name(ev.side)}`;
      if (ev.phase === 'combat') return null;
      return `<b>${clock(ev.turn)}</b> — ход ${ev.turn}: ${name(ev.side)}`;
    case 'rally': {
      const ok = ev.rolls.filter((r) => r.ok).length;
      return ev.rolls.length ? `Приведение в боевое состояние: ${ok} из ${ev.rolls.length}` : null;
    }
    case 'move':
      return `${nm(ev.u)}: ${hx(ev.path[0])} → ${hx(ev.path[ev.path.length - 1])}`;
    case 'wheels':
      return `${nm(ev.u)} — ${ev.on ? 'на колёса' : 'к бою'}`;
    case 'combat':
      return `⚔ Атака на «${nm(ev.log.def)}»: ${ev.a} против ${ev.d} (${ev.log.diff > 0 ? '+' : ''}${ev.log.diff}), кубик ${ev.log.roll} — <b>${ev.log.res}</b>`;
    case 'retreat':
      return `${nm(ev.u)} отступает на ${ev.path.length - 1} — в ${hx(ev.path[ev.path.length - 1])}`;
    case 'hold':
      return `${nm(ev.cmd)} удержал часть «${nm(ev.u)}» (кубик ${ev.roll})`;
    case 'dead':
      return `💥 ${nm(ev.u)} уничтожена (−${U[ev.u].str})`;
    case 'pursue':
      return `${nm(ev.u)} преследует — в ${hx(ev.to)}`;
    case 'wound':
      return ev.res === 'ok' ? null : `${nm(ev.u)}: ${ev.res === 'dead' ? 'убит' : ev.res === 'wounded' ? 'тяжело ранен' : 'легко ранен'}`;
    case 'captured':
      return `${nm(ev.u)} взят в плен`;
    case 'back':
      return `${nm(ev.u)} вернулся в строй`;
    case 'end':
      return `🏁 ${ev.text}`;
  }
  return null;
}

