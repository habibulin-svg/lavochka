const seats2: SeatSpec[] = [0, 1].map((seat) => ({ seat, kind: 'bot', name: SEATS[seat].name, level: 1 }));
const id = (s: string) => U.findIndex((u) => u.id === s);

/** Позиция для показа: только перечисленные части на своих клетках, ход стороны sd в фазе phase. */
function demo(place: Record<string, string>, sd: 0 | 1, phase: State['phase'], steps: DemoScript<State, Action>['steps'], intro?: string, patch?: (s: State) => void): DemoScript<State, Action> {
  return {
    seats: seats2,
    intro,
    setup: () => {
      const s = newState(cfgFrom({}));
      s.u.forEach((st) => (st.hex = -1));
      for (const [k, h] of Object.entries(place)) s.u[id(k)].hex = byLabel(h);
      s.side = sd;
      s.phase = phase;
      s.u.forEach((st, i) => {
        st.mp = U[i].kind === 'art' ? 0 : st.dem ? U[i].mp2 : U[i].mp;
      });
      patch?.(s);
      s.u.forEach((st, i) => {
        if (st.dem && U[i].kind !== 'art') st.mp = U[i].mp2;
      });
      return s;
    },
    steps,
  };
}
