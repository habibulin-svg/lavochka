/* Шпион — темы: слова (words.json собирает tools/spy/build.mjs), вопросы-признаки с вариантами ответа и подборки. Без DOM. */
import WORDS from './words.json';

export interface Word {
  id: string;
  name: string;
  /** Значение каждого вопроса темы (номер варианта ответа). */
  f: number[];
  /** Подпись под названием: автор, год. */
  sub?: string;
  /** Метки подборок: 1 — наше, 2 — зарубежное, 4 — советское, 8 — мультфильм. */
  m?: number;
  /** Локации: роли мирных и вопросы-подсказки. */
  roles?: string[];
  q?: string[];
  /** Есть картинка public/spy/<тема>/<id>.webp. */
  img?: number;
}

export interface Facet {
  /** Вопрос, как его задают вслух. */
  q: string;
  /** Варианты ответа. */
  a: string[];
}

export interface Theme {
  id: string;
  title: string;
  icon: string;
  /** Как назвать загаданное на карточке: «Локация», «Фильм». */
  noun: string;
  facets: Facet[];
  /** Подборки внутри темы (выбор на экране настройки): значение → [подпись, маска меток; 0 — все]. */
  subs?: [string, string, number][];
}

