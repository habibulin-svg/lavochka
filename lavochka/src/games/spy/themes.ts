export const THEME = Object.fromEntries(THEMES.map((t) => [t.id, t])) as Record<string, Theme>;
export const WORDS_OF = WORDS as unknown as Record<string, Word[]>;

/** Слова темы с учётом подборки. */
export function pool(theme: string, sub: string | undefined): Word[] {
  const t = THEME[theme];
  const mask = t.subs?.find((s) => s[0] === sub)?.[2] ?? 0;
  const all = WORDS_OF[theme] ?? [];
  return mask ? all.filter((w) => ((w.m ?? 0) & mask) === mask) : all;
}

export function word(theme: string, id: string): Word | undefined {
  return (WORDS_OF[theme] ?? []).find((w) => w.id === id);
}

