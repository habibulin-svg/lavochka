/**
 * «Корона Эмбера», «Классика 1994» — язык сценариев карт приключений и клеток.
 *
 * Сценарий — массив операций (чистые данные, без DOM и функций: лежит в состоянии партии, ходит по сети).
 * Интерпретатор (`run.ts`) исполняет операции по порядку; операция, которой нужно решение игрока
 * (выбор, бросок кубика, бой), ставит вопрос и ждёт действия. «Ты» в операциях — путник, который
 * выполняет карту.
 *
 * Слова из карт → операции:
 *  «возьми / получи 2 ПС» → add ПС 2;  «ты теряешь 1 ПЖ, 1 ПУ» → add ПЖ −1, add ПУ −1
 *  (потеря идёт через правило компенсации: нечем платить — платишь другим);
 *  «твои 3 ПС переходят в 2 ПУ» → convert;  «брось кубик: 1-3 …» → roll;
 *  «можешь …» → choice;  «если ты честный …» → if;  «X всегда нападает на тебя» → battle;
 *  «отложи карту X» → card discard;  «верни карту в середину колоды» → card middle;
 *  «оставь карту на поле» → card leave;  «поселяется на поле П» → card settle.
 */

export const STATS = ['ПС', 'ПУ', 'ПМ'] as const;
export type Stat = (typeof STATS)[number];
/** Что можно получить или потерять числом. */
export type Pts = Stat | 'ПЖ' | 'ПО' | 'т';
export type World = 'Сила' | 'Ум' | 'Магия' | 'Золото';
export type Align = 'добрый' | 'нейтральный' | 'злой';

/** Вид противника — то, что напечатано в скобках под названием карты. */
export type FoeKind = 'враг' | 'нечисть' | 'зверь' | 'змеи и драконы';

/** Условие для `if`. */
export type Cond =
  | { align: Align | Align[] }
  | { honest: boolean }
  | { patient: boolean }
  | { sex: 'м' | 'ж' }
  /** имеешь: лошадь, друга, любой предмет (не амулет), амулет, магический предмет, шлем, огонь (карманный
   * дракончик), огнестрельное оружие (кольт, бластер, ружьё), трофей (шкура и пр.), деньги, корону регента;
   * или конкретную карту предмета по имени (`item: 'кольт'`) / приключения по номеру (`adv: 66`) */
  | { has: 'horse' | 'friend' | 'item' | 'amulet' | 'magic' | 'helmet' | 'fire' | 'gun' | 'trophy' | 'gold' | 'crown' }
  | { item: string }
  | { adv: number }
  /** собственные пункты: `{ pts: 'ПО', min: 6 }` — не меньше 6; `max` — не больше */
  | { pts: Pts; min?: number; max?: number }
  /** сумма собственных ПС+ПУ+ПМ (без предметов) */
  | { sum: true; min?: number; max?: number }
  /** «если ты выполняешь условия другой карты приключений» (идёшь строго определённым путём, очарован …) */
  | { busy: true }
  /** в каком Мире стоишь */
  | { world: World | World[] }
  | { not: Cond }
  | { any: Cond[] }
  | { all: Cond[] };

/** Ветвь броска: значения или диапазон суммы. */
export interface Branch {
  /** [от, до] включительно — `[1, 3]`; одно значение — `[6, 6]` */
  r?: [number, number];
  /** отдельные значения суммы (рыцарь Оберона: 4, 7, 9, 11) */
  v?: number[];
  /** «во всех остальных случаях» */
  else?: true;
  ops: Op[];
}

/** Куда переместиться. Название поля — как в `cells` (без кавычек, регистр не важен). */
export type Where =
  | { cell: string }
  /** на поле, с которого начал игру (домовой) */
  | { start: true }
  /** на любое поле любого Мира — выбирает игрок */
  | { any: true }
  /** на ближайшее из полей (ураган); равное расстояние — выбор игрока */
  | { nearest: string[] }
  /** кратчайшим путём на поле (лицей, слепец) — фишка идёт туда, «останавливаешься проходом» */
  | { walk: string }
  /** на N полей по часовой стрелке в своём Мире (искривление пространства) */
  | { cw: number }
  /** на N полей в любую сторону — выбор игрока (капуцин) */
  | { steps: number };

/** Что делать с самой картой (или с картой из твоего имущества). */
export type CardFate =
  /** «отложи карту» — в отбой */
  | 'discard'
  /** «верни в середину оставшейся колоды» */
  | 'middle'
  /** «оставь карту на поле, где это случилось» */
  | 'leave'
  /** на соседнее поле (по выбору игрока) */
  | 'adjacent'
  /** взять с собой (в руку): документы, долг, колдовство, шкура-пропуск … */
  | 'keep';

/** Награда за сдачу трофея. */
export interface Sale {
  /** «на поле «Заготконтора» дадут 12 талеров» — cell: 'Заготконтора' */
  cell: string;
  т?: number;
  /** вместо денег — пункты: «дадут 2 ПЖ и 2 ПС» */
  ops?: Op[];
}

/** Трофей: шкура, оружие, пленник. */
export interface Trophy {
  /** как называется на карте: «шкура», «оружие», «крылья», «пленник» … */
  name: string;
  sales: Sale[];
  /** ПО, которые выдаются при сдаче («Затем возьми 2 ПО» после «За шкуру … дадут») */
  po?: number;
  /** пропуск на поле «Пещера сокровищ» */
  pass?: true;
  /** можно носить с собой с пользой (описание из карты; механика — в `special` карты) */
  wear?: string;
}

/** Бой. Противник — сама карта (stats с карты), если не задан `foe`. */
export interface Battle {
  t: 'battle';
  /** свои показатели, если бьётся не противник с карты (призрак, грабитель, охранник) */
  foe?: { name: string; ПС?: number; ПУ?: number; ПМ?: number; kind?: FoeKind };
  /** «бьётся силой против силы в любом из Миров» */
  stat?: Stat;
  /** «сам не нападает (можешь охотиться)» — бой только по желанию, нужно огнестрельное оружие или друг-охотник */
  hunt?: true;
  /** несколько противников: «с каждым поочерёдно» (seq) или «со всеми сразу» (показатели × n) */
  count?: number;
  together?: true;
  /** без помощи: предметов, магических предметов, амулетов, друзей, бронежилета и кольчуги, амулета №7 */
  without?: ('items' | 'magic' | 'amulets' | 'friends' | 'armor' | 'amulet7' | 'weapons')[];
  win: Op[];
  lose: Op[];
  /** ничья — по правилам ничего; если карте нужно своё, задать */
  draw?: Op[];
}

export type Op =
  /** строка в журнал / пояснение игроку */
  | { t: 'say'; s: string }
  /** получить (n > 0) или потерять (n < 0) пункты или талеры */
  | { t: 'add'; p: Pts; n: number }
  /** потерять все: `{ t: 'all', p: 'т' }` — «все талеры», «все ПУ» */
  | { t: 'zero'; p: Pts }
  /** «твои 3 ПС переходят в 2 ПУ»; не хватает — `else` (если задано), иначе компенсация */
  | { t: 'convert'; from: [Pts, number]; to: [Pts, number]; else?: Op[] }
  /** «у тебя остаётся 20 талеров» / «ПЖ до 6» (только вверх: up) */
  | { t: 'set'; p: Pts; n: number; up?: true }
  /** доля денег исчезает, округление вверх (инфляция) */
  | { t: 'tax'; part: number }
  /** бросок: dice — сколько кубиков складывать (2 — «дважды брось кубик»), times — повторить весь бросок N раз */
  | { t: 'roll'; dice?: 1 | 2 | 3; times?: number; br: Branch[] }
  /** «можешь …» — игрок выбирает; первая опция — «да» */
  | { t: 'choice'; q: string; opts: { label: string; ops: Op[]; if?: Cond }[] }
  | { t: 'if'; c: Cond; then: Op[]; else?: Op[] }
  | Battle
  /** переместиться и (если cond) выполнить условия поля */
  | { t: 'move'; to: Where; cond?: true }
  /** пропустить ходы */
  | { t: 'skip'; n: number }
  /** изменить характер: точно (`to`) или на шаг (`step`: +1 к добру, −1 ко злу) */
  | { t: 'align'; to?: Align; step?: 1 | -1 }
  /** завербован Хаосом */
  | { t: 'chaos' }
  /** что сделать с этой картой */
  | { t: 'card'; fate: CardFate }
  /** поселить карту на поле (на выбор из нескольких — по броску сделать через roll) */
  | { t: 'settle'; cell: string }
  /** взять трофей с этой карты */
  | { t: 'trophy'; tr: Trophy }
  /** эта карта становится другом (идёт с тобой) */
  | { t: 'friend'; with: 'вместе' | 'вместо'; hunts?: true; carries?: number }
  /** взять карту предмета с поля предметов (имя как в каталоге; `any: 'amulet'` — любой амулет на выбор) */
  | { t: 'gain'; item?: string; any?: 'amulet' | 'item' | 'item-or-amulet' }
  /** эта карта приключений сама становится предметом / магическим предметом (перстень, зеркало, пентаграмма) */
  | { t: 'own'; magic?: true; po?: number; bonus?: Partial<Record<Stat, number>> }
  /** потерять: предмет (на выбор), магический предмет, амулет, лошадь, друга, лошадь или друга, все предметы,
   * все амулеты, все трофеи, все магические предметы; нечего — компенсация по правилам (если `else` не задан) */
  | { t: 'lose'; what: 'item' | 'magic' | 'amulet' | 'horse' | 'friend' | 'horse-or-friend' | 'items' | 'amulets' | 'trophies' | 'magics' | 'friends' | 'helmet' | 'item-or-amulet'; else?: Op[] }
  /** длительное состояние героя (см. Status) */
  | { t: 'status'; st: Status }
  /** то же со всеми путниками в Мире, где взята карта (или со всеми — `everywhere`), отбирая по `who` */
  | { t: 'each'; who?: Cond; everywhere?: true; ops: Op[] }
  /** состязание: все игроки бросают (dice), наибольший получает ops (`toWinner`) / тебе платить ему (`pay`) */
  | { t: 'contest'; dice: 1 | 2; prize?: number; pay?: number }
  /** выполнить условия поля, на котором стоишь (повторно) */
  | { t: 'cell' }
  /** (для клеток) «возьми N карт» — взять N верхних карт приключений и выполнить по номерам */
  | { t: 'draw'; n: number }
  /** (для клеток) место торговли: можно купить предметы и амулеты, лежащие на этом поле предметов */
  | { t: 'shop' }
  /** закончить сценарий (оставшиеся операции не выполнять) */
  | { t: 'stop' }
  /** особая механика, написанная кодом: id — имя обработчика в `special.ts` */
  | { t: 'special'; id: string; n?: number };

/**
 * Длительные состояния. `turns` — сколько своих ходов действует; без turns — пока не снимется условием.
 */
export type Status =
  /** не можешь покинуть свой Мир (until — поле, после которого снимается; dice — бросок 2d6 перед ходом) */
  | { k: 'world'; turns?: number; until?: string; dice?: number }
  /** парализован: стоишь, пока 2d6 перед ходом не даст ≥ need */
  | { k: 'paralysed'; need: number; po?: number }
  /** ходишь только на чётное число полей */
  | { k: 'even'; turns: number }
  /** ходишь только по часовой (сонная болезнь: 1 или 2 поля по нечет/чёт), пока не попадёшь на поле */
  | { k: 'cw'; until: string; sleepy?: true; po?: number }
  /** перед каждым ходом теряешь пункт, пока не попадёшь на поле (сухотка, дурной глаз, паразиты) */
  | { k: 'drain'; p: Pts; until: string }
  /** называешь число вместо броска: max — до скольки; cards — «можешь выбирать из 2-х карт» */
  | { k: 'name'; turns: number; max: number; cards?: 2 | 3 }
  /** невезение: бросок называет следующий игрок */
  | { k: 'unlucky'; turns: number }
  /** смотришь верхнюю карту перед ходом */
  | { k: 'peek'; turns: number }
  /** невидим: можешь не выполнять карты приключений */
  | { k: 'invisible'; turns: number }
  /** следующий ход — в обратную сторону (чёрная кошка) */
  | { k: 'reverse' }
  /** преследует карта (чёрный двойник, человек-змея): adv — номер карты, which — когда нападает */
  | { k: 'haunt'; adv: number; when: 'turn' | 'snakes' }
  /** нельзя войти в Провал, пока не заплатишь (налог, инспекция, долг, вексель) */
  | { k: 'debt'; т: number; adv?: number; po?: number; to?: 'bank' | 'player' }
  /** без золота, пока не побываешь на поле */
  | { k: 'nogold'; until: string }
  /** амулеты без силы: до поля (магнитная буря) или на N ходов (брукса) */
  | { k: 'noamulets'; until?: string; turns?: number }
  /** предметы без силы до ремонта (магнитный удар) */
  | { k: 'broken' }
  /** собственные ПС, ПУ, ПМ не больше cap, пока не побываешь на поле (воин Хаоса) */
  | { k: 'cap'; n: number; until: string }
  /** маршрут регента: пройти поля по порядку, затем ops */
  | { k: 'route'; cells: string[]; done: number; adv: number }
  /** выбыл по своей воле на N ходов (легион) */
  | { k: 'legion'; turns: number; pay: number }
  /** следующим ходом окажешься на поле (золотоискатель, проклятие на дорогу, авиабилет) */
  | { k: 'fly'; cell: string; then?: Op[] }
  /** книга/папирус: прибавка переходит по 1 за ход */
  | { k: 'study'; p: Stat; left: number };

/** Карта приключений: показатели противника с карты и сценарий встречи. */
export interface AdvDef {
  n: number;
  /** вид из скобок под названием: противник (враг, нечисть, зверь, змеи и драконы), друг, дух, предмет */
  kind?: FoeKind | 'друг' | 'дух' | 'предмет' | 'магический предмет';
  /** показатели из цветных квадратов (ПЖ — у волколака) */
  stats?: { ПС?: number; ПУ?: number; ПМ?: number; ПЖ?: number };
  /** сценарий встречи (что происходит, когда путник взял карту или пришёл на поле, где она лежит) */
  ops: Op[];
  /** если карта ушла с путником (друг, трофей, предмет): что она даёт, описание для особой механики */
  note?: string;
}
