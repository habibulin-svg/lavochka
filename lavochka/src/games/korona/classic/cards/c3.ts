/** Последствия импата для 124 и 125 (кроме выкупа): шлем позволяет не выполнять. */
const impatEffect = (lockWorld: boolean): Op[] => [
  {
    t: 'choice',
    q: 'Шлем защищает от импата — не выполнять условия карты?',
    opts: [
      { label: 'Не выполнять (шлем)', if: { has: 'helmet' }, ops: [{ t: 'card', fate: 'leave' }] },
      {
        label: 'Выполнить условия карты',
        ops: [
          // карта остаётся на поле, где встретил (а не на «Лазарете», куда идёшь потом)
          { t: 'card', fate: 'leave' },
          { t: 'zero', p: 'ПУ' },
          // special ccw_to_lazaret: путник движется ПРОТИВ часовой стрелки по своему Миру до поля «Лазарет» (фишка идёт
          // по полям против часовой стрелки и останавливается на «Лазарете»).  // ? условия поля «Лазарет» выполняются (сказано «движешься … на поле»)
          { t: 'special', id: 'ccw_to_lazaret' },
          ...(lockWorld ? ([{ t: 'status', st: { k: 'world', until: 'Лазарет' } }] as Op[]) : []),
        ],
      },
    ],
  },
];

