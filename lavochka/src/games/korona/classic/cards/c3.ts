/**
 * Карты приключений №101–150 («Корона Эмбера», 1994): сценарии по тексту карт и Приложению к правилам.
 *
 * Общее соглашение для карт, которые «поселяются» на поле или остаются на нём и ведут себя при повторной
 * встрече иначе, чем при первом взятии из колоды:
 * // special on_settled: маркер в списке операций. Всё ДО него — выполняется только когда карта взята из колоды
 * (первое появление); дойдя до маркера, сценарий заканчивается. Всё ПОСЛЕ него — выполняется, когда путник
 * встречает эту карту, лежащую на поле (с самого начала «после маркера»). Карты без маркера при повторной
 * встрече выполняются целиком с начала.
 */

