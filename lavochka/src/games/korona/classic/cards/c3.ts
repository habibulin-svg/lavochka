/** Бой, общий для зверя, который сам не нападает (охота) и нападающего — различается только hunt. */
const catWin: Op[] = [
  {
    t: 'trophy',
    tr: {
      name: 'шкура',
      sales: [
        { cell: 'Заготконтора', т: 5 },
        // Магшоп: останавливаешься там проходом
        { cell: 'Магшоп', ops: [{ t: 'add', p: 'ПУ', n: 2 }] },
      ],
      po: 1,
    },
  },
];
const catBattle = (hunt: boolean): Battle => ({
  t: 'battle',
  ...(hunt ? { hunt: true as const } : {}),
  win: catWin,
  lose: [{ t: 'add', p: 'ПУ', n: -1 }],
});

