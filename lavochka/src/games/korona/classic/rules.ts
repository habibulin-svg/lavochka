import { SeededRng } from '../../../core/rng';
import type { RulesSection } from '../../../core/types';
import { FALL_NEED } from './cells';
import { H, newHero, newState } from './engine';
import type { CState } from './state';

const GUSAR = 15;
const FEYA = 1;
const GLADIATOR = 11;
const seatsOf = (...names: string[]) => names.map((name, seat) => ({ seat, kind: 'bot' as const, name, level: 1 }));
const TWO = seatsOf('Красный', 'Синий');

/** Позиция показа: путники по номерам карт путников, верхняя карта колоды — top (если нужна), правки — tweak. */
function pos(trs: number[], tweak: (s: CState) => void, top?: number): CState {
  const s = newState(
    trs.map((_, seat) => ({ seat, kind: 'bot' as const, name: seat ? 'Синий' : 'Красный', level: 1 })),
    new SeededRng(11),
  );
  trs.forEach((tr, seat) => {
    s.heroes[seat] = newHero(seat, tr, s.shelf);
  });
  s.turn = 0;
  s.log = [];
  if (top != null) s.deck = [top, ...s.deck.filter((n) => n !== top)];
  tweak(s);
  return s;
}

