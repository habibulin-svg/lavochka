/** Нарастающий обмен (усложнённый вариант): 4, 6, 8, 10, 12, 15, 20, дальше +5. */
export function growing(k: number): number {
  const t = [4, 6, 8, 10, 12, 15, 20];
  return k < t.length ? t[k] : 20 + 5 * (k - t.length + 1);
}
