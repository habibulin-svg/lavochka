/** Позиция для показа: все территории у Серёги по 2, кроме перечисленных. */
function demo(spec: [string, number, number][], patch: (s: State) => void, steps: DemoScript<State, Action>['steps'], intro?: string): DemoScript<State, Action> {
  return {
    seats: seats2,
    intro,
    setup: (_d, rng: Rng) => {
      const s = newState(3, cfgFrom({}), rng);
      s.owner = s.owner.map(() => 2);
      s.ships = s.ships.map(() => 2);
      for (const [n, o, k] of spec) {
        s.owner[T(n)] = o;
        s.ships[T(n)] = k;
      }
      s.phase = 'attack';
      s.turn = 0;
      s.pending = 0;
      s.hand = [[], [], []];
      s.goal = [3, 5, 1];
      patch(s);
      syncCounts(s);
      return s;
    },
    steps,
  };
}
