const tn = (t: number) => TERRS[t].name;

function describe(ev: Event, name: (seat: number) => string): string | null {
  switch (ev.type) {
    case 'income':
      if (!ev.n) return null;
      return `${name(ev.seat)}: +${ev.n} звездолётов за планеты ${ev.planets.map((k) => PLANETS[k].name).join(', ')}${ev.ally ? ` (союзнику — ${ev.ally}, поставит соперник)` : ''}`;
    case 'trade':
      return `${name(ev.seat)} меняет карточки на ${ev.n} звездолётов`;
    case 'roll':
      return `${name(ev.seat)}: ${tn(ev.from)} → ${tn(ev.to)} — ${ev.a.join(' ')} против ${ev.d.join(' ')}${ev.lostA ? `, −${ev.lostA} у нападения` : ''}${ev.lostD ? `, −${ev.lostD} у защиты` : ''}`;
    case 'conquer':
      return `${name(ev.seat)} осваивает <b>${tn(ev.to)}</b>${ev.card ? ' и берёт карточку' : ''}`;
    case 'out':
      return `💥 ${name(ev.seat)} выбывает${ev.cards ? ` — ${ev.cards} карточек переходят к ${name(ev.by)}` : ''}`;
    case 'move':
      return `${name(ev.seat)} перемещает ${ev.n}: ${tn(ev.from)} → ${tn(ev.to)}`;
    case 'end':
      return `🏁 Победа: ${ev.winners.map(name).join(', ')} — ${ev.text}`;
  }
  return null;
}

