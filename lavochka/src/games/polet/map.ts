/* «Полёт» — разметка маршрута на поле (public/polet/board.webp, 2400×1920; снято вручную по увеличенным фрагментам).
 * Точки — цветные с номерами и чёрные без номеров; ход считается по всем. Основной маршрут — 1…27; обходы (тонкая линия):
 * у 7 (гроза), у 14 (обледенение), у 16 (запасной аэродром 19); у 21 — зона ожидания, у 26 — второй круг. Без DOM. */

export interface Pt {
  /** Номер на поле (0 — чёрная точка). */
  n: number;
  x: number;
  y: number;
}

export const PTS: Pt[] = [];
const ID = new Map<string, number>();
function p(name: string, n: number, x: number, y: number): number {
  ID.set(name, PTS.length);
  PTS.push({ n, x, y });
  return PTS.length - 1;
}
export const pt = (name: string) => ID.get(name)!;

