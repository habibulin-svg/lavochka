const seq = (s: string) => s.split(' ').map(pt);

/** Участки: имя → точки по порядку. Самолёт летит по участку, в конце переходит на `next` с указанной точки. */
export interface Leg {
  pts: number[];
  /** Куда дальше: участок и номер точки в нём (с неё продолжается полёт). */
  next?: [string, number];
}
