/** Воин Велимир у Форпоста и бой с двумя ортами (по 3 ОР) — для показа боя. */
function fightDemo(_def: GameDef, rng: Rng): State {
  const s = setup(SEATS, { quick: true }, rng);
  const h = s.heroes[0];
  Object.assign(h, {
    name: 'Велимир', cls: 'voin', level: 0, xp: 0, hp: 9, hpMax: 9, gold: 70, portrait: 'voin', pending: [], kills: [],
    stats: { str: 15, dex: 12, wis: 10, con: 13, brv: 11 }, base: { str: 15, dex: 12, wis: 10, con: 13, brv: 11 },
    items: [{ id: 'sword_long', n: 1 }, { id: 'kolch_iron', n: 1 }, { id: 'shield', n: 1 }],
    eq: { melee: 'sword_long', armor: 'kolch_iron', shield: 'shield' },
    create: { step: 'done', rerolls: 0 },
  });
  s.scene = null;
  s.where = { k: 'map', node: MAP.start };
  s.story = [];
  s.phase = 'travel';
  s.custom = [{ say: 'Из-за поворота выходят двое ортов: «А ну стой! Не глоки ли вы?» — и, не дожидаясь ответа, хватаются за тесаки.' }, { fight: [{ m: 'ort', n: 2, hp: 3 }], win: [{ say: 'Орты повержены. Дорога свободна.' }] }];
  startScene({ s, rng, ev: [] }, 'custom');
  return s;
}

