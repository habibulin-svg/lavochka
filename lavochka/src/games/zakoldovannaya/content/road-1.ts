/* «Прочее» — дорожные встречи книги ведущего, 1–62 (книга, с. 40–42). gm — дословно книга, для игроков — то, что видят герои.
 * Метки: night — книга говорит «ночью»; castle — «у самого замка»; bridge — «на мосту»; forpost — «дорога от города Форпоста».
 * Где книга молчит (сколько платить, что делает встречный) — решение в духе правил, отмечено «в книге не сказано». */
import { ask, chest, fight, type Foe, type Scene, type Step } from '../script';

const road = (n: number, title: string, gm: string, steps: Step[], more: Partial<Scene> = {}): Scene => ({ id: `road:${n}`, title, gm, ...more, steps });

/** Бой, где опасность нападает сразу. */
const ambush = (foes: Foe[] | string, win?: Step[]): Step => fight(foes, { first: 'foes', ...(win ? { win } : {}) });

/** Просто имя опасности: проверка агрессивности (d6): 1 — спят, 2 — замечают, но не нападают, 3–4 — грубят (решают герои), 5–6 — нападают. */
function meet(foes: Foe[], t: { calm: string; notice: string; rude: string; attack: string }, win?: Step[]): Step {
  const rude: Step[] = [
    t.rude,
    ask('Что ответите?', [
      { text: 'Не связываться, пройти мимо', bot: 2, do: ['Вы молча проходите мимо, пропуская грубости мимо ушей.'] },
      { text: 'Ответить тем же', risky: true, do: [fight(foes, win ? { win } : {})] },
    ]),
  ];
  return { aggression: [[t.calm], [t.notice], rude, rude, [t.attack, ambush(foes, win)]] };
}

/** То же с общими словами: who — «Варги» (pl) / «Циклоп» (не pl). */
const meetOf = (foes: Foe[], who: string, pl: boolean, win?: Step[]): Step =>
  meet(
    foes,
    pl
      ? { calm: `${who} дремлют и не замечают вас.`, notice: `${who} замечают вас, но не нападают.`, rude: `${who} грубят и загораживают путь.`, attack: `${who} с рыком бросаются на вас!` }
      : { calm: `${who} дремлет и не замечает вас.`, notice: `${who} замечает вас, но не нападает.`, rude: `${who} грубит и загораживает путь.`, attack: `${who} с рыком бросается на вас!` },
    win,
  );

