import { ask, fight, opt, type Foe, type Site, type Step } from '../script';

/** Хромой эльф-пикси: говорит много, врёт наполовину («на вопросы врёт 50%») — просто болтовня без последствий. */
function pixi(first: string): Step[] {
  return [
    first,
    ask('Расспросить его?', [
      opt('Расспросить о замке', {
        random: [
          ['«Чёрного мага нет дома, он уехал на ярмарку! — частит эльф. — Ходите где хотите, ничего не бойтесь!»'],
          ['«Тут за каждой дверью по дракону, — шепчет эльф, округляя глаза. — Мне ли не знать!»'],
        ],
      }),
      opt('Не слушать', 'Вы отмахиваетесь от болтуна.'),
    ]),
  ];
}

/** Встречный, про которого в книге только имя: проверка агрессивности (d6 — 1 спит, 2 замечает, 3–4 грубит, 5–6 нападает). */
function aggr(foes: Foe[], sleep: string, notice: string, rude: string): Step {
  const rudeBranch: Step[] = [rude, ask('Что делаете?', [opt('Отступить', 'Вы медленно пятитесь прочь.', { end: true, repeat: true }), opt('Драться', fight(foes))])];
  return { aggression: [[sleep], [notice], rudeBranch, rudeBranch, [rude, fight(foes, { first: 'foes' })], [rude, fight(foes, { first: 'foes' })]] };
}

/** Молния Чёрного мага (БУ 12, иначе смерть); если в 25 повезло со щелью — «смягчить участь»: БУ 8. */
function lightning(who: 'random' | 'subject' = 'random'): Step {
  const dead: Step[] = [{ kill: 'subject', say: 'Молния попадает в {name} — и от героя остаётся только горсть пепла.' }];
  const mk = (need: number): Step => ({
    roll: { kind: 'save', need, save: 'lightning', who, label: 'Бросок удачи от молнии' },
    pass: ['{name} успевает нырнуть в сторону — молния бьёт в камень.'],
    fail: dead,
  });
  return { if: { flag: 'c10.luck' }, then: [mk(8)], else: [mk(12)] };
}

