/** Гнома освободили: флаг и строфа песни звена; троих освободили — пора собираться. */
const freed = (id: string, verse: string): Step[] => [
  { set: `k3.g_${id}` },
  { set: `k3.${verse}` },
  { if: { all: [atLeast(3, GN), notFlag('gn3')] }, then: [{ set: 'k3.gn3' }] },
];

/** Снять цепь: ключи, «Отпирание» или молоточек Тимофея — сразу; иначе сила или упорство. */
const unchain = (need: number, ok: Step[], fail: Step[]): Step => ({
  if: { any: [{ item: 'keys', who: 'any' }, { spell: 'otpiranie', who: 'any' }, flag('zp_hammer')] },
  then: ['Цепь поддаётся: ключ или рунный молоточек — и звенья одно за другим падают на пол.', ...ok],
  else: [
    {
      roll: { kind: 'stat', need, stat: 'str', who: 'best:str', label: `Разорвать цепь (сила ${need})` },
      pass: ['{name} берётся за звено двумя руками, надувается, краснеет — и цепь лопается с громким звоном.', ...ok],
      fail: [
        'Рвать не получается: звенья слишком крепкие. Остаётся подпиливать.',
        {
          roll: { kind: 'd6', need: [5, 6], who: 'leader', label: 'Подпилить звено', tries: 3 },
          pass: ['Пилка скрипит, пот льётся, но звено наконец поддаётся.', ...ok],
          fail,
        },
      ],
    },
  ],
});

