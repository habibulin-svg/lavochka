type BookRoom = (typeof c10.rooms)[string];
const book = (n: string): BookRoom => c10.rooms[n];

/** Комната c10: с Посохом — свои шаги, без Посоха — как в книге. */
function staffRoom(id: string, n: string, title: string, withStaff: Step[], extra: Partial<Parameters<typeof cs>[1]> = {}) {
  const b = book(n);
  return cs(id, {
    title,
    ...(b.gm ? { gm: b.gm } : {}),
    ...(b.img ? { img: b.img } : {}),
    steps: [{ if: F('k1.staff'), then: withStaff, else: b.steps }],
    ...(b.nodes ? { nodes: b.nodes } : {}),
    ...(b.after ? { after: b.after } : {}),
    ...extra,
  });
}

