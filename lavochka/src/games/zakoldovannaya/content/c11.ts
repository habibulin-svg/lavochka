import type { Scene, Site, Step } from '../script';

/** Сцена со сверхопасностью: n — номер в книге, m — id опасности, name — имя из книги, gold — деньги из списка. */
function sup(n: number, m: string, name: string, bookName: string, gold: number, intro: string, win: string, extra: Step[] = []): Scene {
  return {
    id: `site:c11:${n}`,
    title: bookName,
    gm: `${n} ${bookName} — ${gold} монет. (Стоимость удваивается; +2 жизненных кубика; аморальные.)`,
    img: m,
    steps: [
      intro,
      {
        fight: [{ m, name, extraHd: 2, valueMul: 2, morale: 'am' }],
        win: [win, { give: { gold } }, ...extra],
        fled: ['Вы отступаете, не оглядываясь. Тварь остаётся стеречь комнату.', { end: true, repeat: true }],
      },
    ],
    after: 'Пустая поляна. Следы недавней схватки.',
  };
}

