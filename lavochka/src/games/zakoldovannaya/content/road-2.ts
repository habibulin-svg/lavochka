/* «Прочее» — дорожные встречи книги ведущего, 63–124. Номер сцены 'road:N' = номер пункта книги.
 * gm — дословно книга (только очевидные опечатки распознавания исправлены); для игроков — то, что видят герои. */
import { ask, fight, opt, type Fight, type Foe, type Scene, type Step } from '../script';

const GO_ON = 'Вы молча идёте своей дорогой, не оглядываясь.';

const sc = (n: number, title: string, gm: string, steps: Step[], o: { img?: string; tags?: string[] } = {}): Scene => ({
  id: `road:${n}`,
  title,
  gm,
  ...(o.img ? { img: o.img } : {}),
  steps,
  ...(o.tags ? { tags: o.tags } : {}),
});

/** Встречные, о нравах которых книга молчит («Липучка.», «2 фурона»): ведущий кидает d6 — агрессивность.
 * 1 — не замечают, 2 — замечают, но не нападают, 3–4 — грубят (можно уйти или принять вызов), 5–6 — нападают. */
function meet(foes: Foe[], t: { sleep: string; notice: string; rude: string; attack: string; leave?: string }, extra: Omit<Fight, 'fight' | 'first'> = {}): Step {
  const rude = (): Step[] => [t.rude, ask('Что делаете?', [{ ...opt('Пройти мимо', t.leave ?? GO_ON), bot: 2 }, { ...opt('Принять вызов', fight(foes, extra)), risky: true }])];
  return { aggression: [[t.sleep], [t.notice], rude(), rude(), [t.attack, fight(foes, { ...extra, first: 'foes' })]] };
}


