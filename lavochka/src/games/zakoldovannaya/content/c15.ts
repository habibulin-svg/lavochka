import { ask, chest, fight, opt, type Foe, type Site, type Step } from '../script';

/** Эльф-пикси: «большой охотник поболтать», на вопросы врёт в половине случаев — болтовня без последствий. */
function pixi(first: string): Step[] {
  return [
    first,
    ask('Расспросить его?', [
      opt('Спросить, что наверху', {
        random: [
          ['«Наверху вас ждёт целая гора золота! — выпаливает эльф. — Поднимайтесь смелее!»'],
          ['«Наверх лучше не ходить, — шепчет эльф и оглядывается. — Там вас никто не ждёт».'],
        ],
      }),
      opt('Не слушать', 'Вы отмахиваетесь от болтуна.'),
    ]),
  ];
}

/** Встречный, про которого в книге только имя: проверка агрессивности (d6 — 1 спит, 2 замечает, 3–4 грубит, 5–6 нападает). */
function aggr(foes: Foe[], sleep: string, notice: string, rude: string): Step {
  const rudeBranch: Step[] = [rude, ask('Что делаете?', [opt('Отступить', 'Вы медленно пятитесь прочь.', { end: true, repeat: true }), opt('Драться', fight(foes, { fled: [{ end: true, repeat: true }] }))])];
  return { aggression: [[sleep], [notice], rudeBranch, rudeBranch, [rude, fight(foes, { first: 'foes' })], [rude, fight(foes, { first: 'foes' })]] };
}

