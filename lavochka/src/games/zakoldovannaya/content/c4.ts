/** Бутылки в винном погребе трактира (5.6): номер книги → что случается с тем, кто отхлебнул. */
const sip = (n: number): Step[] => {
  const eff: Record<number, Step> = {
    1: give({ bottles: [1] }, 'subject', '{name} не торопится пить — прячет бутылку в сумку.'),
    2: give({ hp: -1 }),
    3: give({ hp: -2 }),
    4: give({ hp: -3 }),
    5: give({ hp: 1 }),
    6: give({ hp: 2 }),
    7: give({ hp: 3 }),
    8: give({ heal: 'full' }),
    9: { kill: 'subject', say: '{name} хрипит, хватается за горло и падает на пол.' },
    13: give({ stat: ['dex', 3] }),
    15: give({ stat: ['dex', -2] }),
    17: give({ stat: ['str', 3] }),
    19: give({ stat: ['wis', -3] }),
    22: give({ stat: ['con', 3] }),
  };
  return ['{name} отхлёбывает из бутылки.', eff[n]];
};
