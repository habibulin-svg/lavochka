function describe(ev: Event, name: (seat: number) => string): string | null {
  if (ev.type === 'answer') return ev.ok ? `${name(ev.seat)}: ответ верный.` : `${name(ev.seat)}: неверно (верно — «${ev.right}»).`;
  if (ev.type === 'move' && ev.incident) return `☄ ${name(ev.seat)}: ${ev.incident}. ${INC[ev.incident]}.`;
  if (ev.type === 'land') return `🪐 ${name(ev.seat)}: посадка — ${PLANET_NAME[ev.planet]}${ev.passive ? ' (планета подошла сама)' : ''}!`;
  if (ev.type === 'ac') return ev.arrived ? `${name(ev.seat)}: автоматическая станция доставила топливо.` : null;
  if (ev.type === 'wait') return `${name(ev.seat)} бережёт топливо и пропускает ход.`;
  if (ev.type === 'skip') return `${name(ev.seat)} пропускает ход.`;
  if (ev.type === 'end') return ev.winner == null ? '🏁 Полёт окончен.' : `🏁 ${name(ev.winner)} — лучший капитан: вернулся на Землю!`;
  return null;
}

