const money = (n: number) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');

function text(kind: Kind, n?: number, pt?: Pt): string {
  switch (kind) {
    case 'start':
      return 'Отсюда начинают «малый бизнес». Пройдя «наследство», здесь останавливаются: следующим ходом — без кубика в аэропорт или ещё круг (до покупки первой фирмы — не больше трёх кругов подряд, после — двух).';
    case 'air':
      return 'Из аэропорта бросают кубик и идут по «большому бизнесу» от «Телекса». Забастовка в аэропорту — никто не летит.';
    case 'patent':
      return `Патент «${PT_NAME[pt!]}»: банк платит сумму с оборота патента (от ${money(Math.min(...PATENTS[pt!]))} до ${money(Math.max(...PATENTS[pt!]))}). Патенты — залог для кредита.`;
    case 'izv':
      return 'Возьмите карточку «Известие».';
    case 'telex':
      return 'Возьмите карточку «Телекс».';
    case 'tax':
      return `Налог ${money(n!)}. ${n! < 150000 ? 'На первом круге малого бизнеса не берётся. ' : ''}Благотворителю — скидка.`;
    case 'treasure':
      return `Клад ${money(n!)} — только с ключом: бросьте кубик трижды, за каждое выпавшее число-ключ — по ${money(n!)}.`;
    case 'rest':
      return `Отдых: пропустите ${n} ${n === 2 ? 'хода' : 'хода'}.`;
    case 'racket':
      return 'Рэкет отбирает все патенты. Попадёте на «Милицию» — вернут.';
    case 'fire':
      return 'Пожар: без страхового полиса сгорают все патенты и предприятия (право на фирмы остаётся).';
    case 'police':
      return 'Милиция возвращает патенты, отнятые рэкетом.';
    case 'exchange':
      return 'Биржа: дважды крутите указатель — фирма и изменение курса. Работает после первой покупки фирмы.';
    case 'bank':
      return n === 1
        ? 'Банк кредитует по 300 000 за каждый патент после 3-го, после 8-го — по половине. Патенты отдаются банку.'
        : 'Банк кредитует по 500 000 за каждый патент после 5-го, после 10-го — по половине. Патенты отдаются банку.';
    case 'casino':
      return `Казино: бросьте кубик. Чётное — выигрыш ${money(n!)}, нечётное — столько же проигрыша.`;
    case 'shadow':
      return `Теневая экономика предлагает ${money(n!)}. Взявший получает карточку теневика — с карточкой фининспектора в суде он теряет всё.`;
    case 'subsidy':
      return `Государственная безвозвратная субсидия: получите ${money(n!)}.`;
    case 'school':
      return `Школа бизнеса: плата за обучение ${money(n!)} и пропуск хода. Диплом менеджера удваивает прибыль с вашей собственности.`;
    case 'insure':
      return `Страховой полис за ${money(n!)}: пожар и ограбление вам не страшны.`;
    case 'inherit':
      return `Получите наследство ${money(n!)}. Дальше — остановка на «Начале».`;
    case 'firm':
      return '';
    case 'inspector':
      return 'Финансовый инспектор: теневик получает карточку фининспектора.';
    case 'court':
      return 'Суд: у теневика с карточкой фининспектора конфискуют всё — деньги, патенты и собственность, и он пропускает ходы. Второй раз — выбывает.';
    case 'robbed':
      return 'Вас ограбили: без страхового полиса пропадают все деньги.';
    case 'strike':
      return 'Забастовка на ваших предприятиях: уйти можно, выбросив чётное. Пока стоите здесь, ваши предприятия прибыли не приносят.';
    case 'charity':
      return `Благотворительный аукцион: начальная цена ${money(n!)} — кто больше? Взнос даёт налоговую льготу.`;
    case 'club':
      return 'Клуб бизнесменов — конец круга «большого бизнеса». Следующим ходом — снова большой бизнес или назад в малый.';
  }
}

function build(): Cell[] {
  const out: Cell[] = [];
  const add = (r: Raw) => {
    const [name, kind, x, y, extra] = r;
    const c: Cell = { id: out.length, name, kind, x, y, text: '' };
    if (typeof extra === 'number') c.n = extra;
    else if (typeof extra === 'string') c.pt = extra;
    else if (extra) c.firm = extra;
    c.text = text(kind, c.n, c.pt);
    out.push(c);
  };
  add(['Начало', 'start', 2830, 2380]);
  SMALL.forEach(add);
  add(['Аэропорт', 'air', 300, 250]);
  BIG.forEach(add);
  return out;
}

