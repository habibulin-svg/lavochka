function fishek(n: number): string {
  const m = n % 10;
  const t = n % 100;
  return `${n} ${m === 1 && t !== 11 ? 'фишка' : m >= 2 && m <= 4 && (t < 12 || t > 14) ? 'фишки' : 'фишек'}`;
}

function describe(ev: Event, name: (seat: number) => string): string | null {
  if ((ev.type === 'move' || ev.type === 'stop') && ev.taken.length) return `⚔️ ${name(ev.seat)}: взято в клещи — ${ev.taken.length}.${ev.type === 'move' && ev.bonus ? ' Ещё ход!' : ''}`;
  if (ev.type === 'phase') return 'Войска расставлены — начинается бой.';
  if (ev.type === 'end') {
    if (ev.why === 'all') return `🏁 У соперника не осталось войска — победа: ${name(ev.winner!)}.`;
    if (ev.why === 'dux') return `🏁 Дукс заперт — победа: ${name(ev.winner!)}.`;
    if (ev.why === 'stuck') return `🏁 Сопернику некуда ходить — победа: ${name(ev.winner!)}.`;
    if (ev.why === 'quiet') return ev.winner == null ? '🏁 Долго без взятий, фишек поровну — ничья.' : `🏁 Долго без взятий — у кого больше фишек, тот и выиграл: ${name(ev.winner)}.`;
    return '🏁 Пятьсот полуходов — ничья.';
  }
  return null;
}

const demoSeats: SeatSpec[] = [0, 1].map((seat) => ({ seat, kind: 'bot', name: SEATS[seat].name, level: 1 }));
/** Позиция: [x, y, фишка] (1, 2 — простые, 3, 4 — дуксы), чей ход. */
function pos(cells: [number, number, number][], turn: number, o: Options = {}): State {
  const s = newState(cfgFrom(o));
  s.board.fill(0);
  for (const [x, y, v] of cells) s.board[at(s, x, y)] = v;
  s.phase = 'play';
  s.hand = [0, 0];
  s.duxHand = [false, false];
  s.turn = turn;
  s.ply = 4;
  return s;
}
const Mv = (seat: number, x: number, y: number, x2: number, y2: number, caption?: string, w = 8) => ({ seat, action: { type: 'move', from: y * w + x, to: y2 * w + x2 } as Action, caption });
const Pl = (seat: number, x: number, y: number, caption?: string) => ({ seat, action: { type: 'place', to: y * 8 + x } as Action, caption });

function fixedRng(seed: number): Rng {
  let x = seed;
  return {
    next: () => (x = (x * 1103515245 + 12345) % 2147483648) / 2147483648,
    int(n: number) {
      return Math.floor(this.next() * n);
    },
    getState: () => x,
  };
}

