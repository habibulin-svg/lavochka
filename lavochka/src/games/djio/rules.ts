/** Карточки ситуаций: что написано и что из этого следует в игре. */
export type CardEffect =
  /** Взять предметы (choose — выбрать один из списка), деньги, лошадь. */
  | { k: 'give'; items?: ItemId[]; choose?: ItemId[]; horse?: boolean; money?: number }
  /** Потерять предметы (all — всё, кроме оружия и аппаратуры), лошадь, деньги. */
  | { k: 'lose'; items?: ItemId[] | 'all'; horse?: boolean; money?: number; keepWeapons?: boolean }
  /** Нужна вещь: есть — ничего, нет — ждать грань кубика или погибнуть. */
  | { k: 'need'; item: ItemId; alt?: ItemId; wait?: number; die?: boolean }
  /** Стрелять: попаданий нужно столько-то, иначе смерть. */
  | { k: 'shoot'; hits: number }
  /** Откуп у туземцев: подарки, 10 000, вещь, лошадь или дымовая шашка — иначе смерть. */
  | { k: 'natives' }
  /** Базар: выбрать одну вещь за цену. */
  | { k: 'buy'; choose: ItemId[]; price: number }
  /** Ничего не случилось. */
  | { k: 'safe' };

export interface Card {
  n: number;
  title: string;
  text: string;
  effect: CardEffect;
}

