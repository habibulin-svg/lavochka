/** Узел «Игрушки» (30×14). */
const A = (c: number, r: number) => r * 30 + c;

/** Позиция: самолёты [сторона, тип, узел, курс] — взлетевшие. */
function pos(ver: 'a' | 'b', list: [number, 'b' | 'f', number, Dir][], side = 0): State {
  const s = newState(cfgFrom({ ver }), 2);
  s.planes = list.map(([sd, kind, p, dir], id) => ({ id, side: sd, kind, p, dir, up: true }));
  s.side = side;
  return s;
}
