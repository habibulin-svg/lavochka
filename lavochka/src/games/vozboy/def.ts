const KIND = { b: 'бомбардировщик', f: 'истребитель' };

function describe(ev: Event, name: (seat: number) => string): string | null {
  if (ev.type === 'fly') {
    let t = `${name(ev.seat)}: ${KIND[ev.kind]} — ${ev.seq.includes('F') ? 'полёт' : 'разворот'}`;
    if (ev.took) t += ` — сбит ${KIND[ev.took.kind]}!`;
    if (ev.shot >= 0) t += ' — 💥 сбит зениткой';
    if (ev.hq && ev.shot < 0) t += ' — 💣 штаб разбомблен!';
    return t;
  }
  if (ev.type === 'end') return ev.winner == null ? `🏁 Ничья: ${WHY[ev.why]}.` : `🏁 Победа — ${name(ev.winner)}: ${WHY[ev.why]}!`;
  return null;
}

