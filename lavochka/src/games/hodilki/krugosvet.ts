const AGAIN = [7, 14, 31, 51, 58, 77, 95, 109, 113];
const BACK: Record<number, number> = { 27: 17, 48: 41, 68: 55, 71: 62, 100: 46, 107: 37 };
const FWD: Record<number, number> = { 24: 52, 47: 61, 70: 80, 91: 99 };

function sign(i: number): Sign | null {
  if (AGAIN.includes(i)) return { k: 'again' };
  if (i === 21) return { k: 'start' };
  if (BACK[i]) return { k: 'jump', to: BACK[i], good: false, text: `откатывается назад, на ${BACK[i]}` };
  if (FWD[i]) return { k: 'jump', to: FWD[i], good: true, text: `мчится вперёд, на ${FWD[i]}` };
  return null;
}

