/** Клетки поля: 140 пронумерованных, потом безномерные участки (дороги Распутья, обход, круги). */
function shelCells(): Cell[] {
  const cells: Cell[] = raw.cells.map((c, i) => ({ x: c.x, y: c.y, sign: null, label: String(i + 1) }));
  for (const name of PART_ORDER) for (const p of PARTS[name]) cells.push({ x: p.x, y: p.y, sign: null, off: true });
  const choice = (n: number, title: string, text: string, options: ChoiceOption[]) => {
    cells[at(n)].sign = { k: 'choice', title, text, options, self: true };
  };
  raw.cells.forEach((c, i) => {
    if (c.s === 'market') cells[i].sign = { k: 'market', text: 'Ярмарка чудес' };
    if (c.s === 'skip') choice(i + 1, 'Привал', 'Трудная дорога домой — солдат остановился на привал.', REST);
  });
  for (const sk of SKIPS) {
    cells[at(sk.at)].sign = { k: 'skip' };
    cells[at(sk.at)].text = sk.text;
  }
  for (const bar of BARS) {
    // вход в круги Лешего — первый кружок круга
    const options = bar.options.map((o) => (o.toCell === -1 ? { ...o, toCell: LOOPS[0].cells[0] } : o));
    for (const n of bar.at) choice(n, bar.title, bar.text, options);
  }
  // Распутье: встал ровно на 4 — выбираешь одну из трёх дорог (проскочил — идёшь дальше по номерам)
  choice(
    4,
    'Распутье',
    'Встал на Распутье — дальше по ненумерованным полям, дорога удлинится. Выбирай любую из трёх, но на каждой ждут неприятности.',
    FORK_ROADS.map((r, k) => ({ text: r.label, route: k, text2: `Солдат свернул: ${r.label.toLowerCase()}.` }))
  );
  cells[at(4)].roads = FORK_ROADS.map((r) => [...partIdx[r.part], at(5)]);
  // красные кружки на дорогах — «неприятности»: пропуск хода
  for (const r of FORK_ROADS)
    for (const k of r.red) {
      const c = cells[partIdx[r.part][k]];
      c.sign = { k: 'skip' };
      c.text = 'Неприятности на дороге Распутья:';
    }
  // обход Огненной реки: кружки вдоль скал, выход на 38
  cells[at(37)].roads = [[...partIdx.river, at(38)]];
  // круги Пастуха: встал на 133 — уходишь на кружки (у Лешего вход — вариант выбора на 64/65)
  cells[at(133)].sign = {
    k: 'loop',
    cells: LOOPS[1].cells,
    exit: LOOPS[1].exit,
    out: LOOPS[1].out,
    text: 'Злой Пастух: тут уж ничем не поможешь — кружит солдата, пока сам не выйдет (нечётным броском)',
  };
  return cells;
}

