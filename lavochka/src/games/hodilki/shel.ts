/** Безномерные кружки поля (data/shel-branches.json) — идут в списке клеток сразу за лентой, в этом порядке. */
const PARTS = branches.parts as Record<'forkLow' | 'forkMid' | 'forkUp' | 'river' | 'leshiy' | 'pastukh', { x: number; y: number }[]>;
const PART_ORDER = ['forkLow', 'forkMid', 'forkUp', 'river', 'leshiy', 'pastukh'] as const;
/** Индексы клеток участка в общем списке клеток. */
const partIdx: Record<string, number[]> = {};
{
  let k = raw.end + 1;
  for (const name of PART_ORDER) partIdx[name] = PARTS[name].map(() => k++);
}

/** Клетка по номеру с поля (1…140) → индекс в списке. */
const at = (n: number) => n - 1;
const needName = (id: CardId) => SHEL_CARDS.find((c) => c.id === id)?.name ?? id;

/** Вариант «пройти предметом»: предмет уходит в общий запас (волшебные — одноразовые), `keep` — остаётся у солдата. */
const use = (card: CardId, text: string, more: Partial<ChoiceOption> & { keep?: boolean } = {}): ChoiceOption => {
  const { keep, ...rest } = more;
  return {
    text: `${needName(card)}: ${text}`,
    need: card,
    ...(keep ? {} : { pay: [card] }),
    text2: 'Волшебство выручило — путь свободен.',
    ...rest,
  };
};
/** Хлеб (или скатерть-самобранка — она кормит сколько угодно раз). */
const feed = (text: string, more: Partial<ChoiceOption> = {}): ChoiceOption[] => [
  { text: `Хлеб: ${text}`, need: 'bread', pay: ['bread'], text2: 'Краюха пригодилась.', ...more },
  { text: `Скатерть-самобранка: ${text}`, need: 'tablecloth', text2: 'Скатерть-самобранка накормила.', ...more },
];
const lose = (n: number, text = 'Пройти нечем'): ChoiceOption => ({
  text: `${text} — потерять ${n} ${n === 1 ? 'ход' : 'хода'}`,
  skip: n,
  text2: 'Пришлось переждать.',
});
/** Назад на клетку n (номер с поля). */
const back = (n: number, text: string, text2 = `Пришлось вернуться на ${n}.`): ChoiceOption => ({ text: `${text} — назад на ${n}`, to: n, text2 });
/** На заработки к волшебной печи (106): два хода работы — и краюха в котомке. */
const work = (text = 'Хлеба нет'): ChoiceOption => ({
  text: `${text} — на заработки к печи (106): два хода, зато краюха`,
  to: 106,
  skip: 2,
  get: ['bread'],
  text2: 'Два хода на заработках у печи — и краюха в котомке.',
});

