const lerp = (pts: [number, number][], t: number, log = false) => {
  if (t <= pts[0][0]) return pts[0][1];
  for (let i = 1; i < pts.length; i++) {
    const [x1, y1] = pts[i];
    const [x0, y0] = pts[i - 1];
    if (t <= x1) {
      const u = (t - x0) / (x1 - x0);
      return log ? Math.exp(Math.log(y0) + (Math.log(y1) - Math.log(y0)) * u) : y0 + (y1 - y0) * u;
    }
  }
  return pts[pts.length - 1][1];
};
