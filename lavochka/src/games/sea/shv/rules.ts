export function describeShv(e: ShvEvent, name: (seat: number) => string): string | null {
  switch (e.t) {
    case 'qspin': {
      const sec = sectionOf(e.book, e.q);
      return `${name(e.seat)}: ${BOOKS[e.book].title}, №${e.q} — ${sec.title.toLowerCase()}${e.letters ? `, на букву ${e.letters.split('').join('/')}` : ''}`;
    }
    case 'answer':
      return e.how === 'giveup'
        ? `${name(e.seat)} не знает ответа`
        : e.how === 'letter'
          ? `${name(e.seat)}: «${esc(e.text)}» — не на ту букву`
          : e.how === 'wait'
            ? `${name(e.seat)}: «${esc(e.text)}» — такого слова в словаре нет, решают другие`
            : `${name(e.seat)}: «${esc(e.text)}»${e.how === 'honor' ? ' — засчитано на честном слове' : ''}`;
    case 'judged':
      return `${name(e.seat)}: ${e.ok ? 'засчитано' : 'не засчитано'}`;
    case 'quiz':
      return e.ok
        ? e.why === 'start'
          ? `${name(e.seat)} выдержал экзамен — капитан!`
          : e.gain
            ? `${name(e.seat)}: верно, +${e.gain} марок`
            : `${name(e.seat)}: верно`
        : `${name(e.seat)}: ответ не засчитан`;
    case 'compass':
      return `${name(e.seat)}: компас — ${e.n}`;
    case 'pay':
      return e.half ? `${name(e.seat)}: марок нет — вдвое меньше узлов` : null;
    case 'point':
      if (e.kind === 'port') return `${name(e.seat)}: ${PORTS[e.node]?.name ?? ''}`;
      if (e.kind === 'fire') return `${name(e.seat)}: пожар на корабле (пункт 15) — за борт ${e.n} марок`;
      if (e.kind === 'lotsman')
        return e.node === 'P_GROT'
          ? `${name(e.seat)} освободил Великого Лоцмана — вымпел на борту!`
          : `${name(e.seat)} уступает пункт кораблю с вымпелом — назад на 4 узла`;
      return POINT_TEXT[e.kind] ? `${name(e.seat)}: ${POINT_TEXT[e.kind]}` : null;
    case 'skip':
      return e.why === 'skip' ? `${name(e.seat)} пропускает ход` : e.why === 'reef' ? `${name(e.seat)} на рифах` : e.why === 'plen' ? `${name(e.seat)} в плену` : null;
    case 'back':
      return e.why === 'tow' ? `${name(e.seat)} отходит на 4 узла — плата за буксир` : null;
    case 'pirates':
      return e.paid === null ? `${name(e.seat)} захвачен пиратами — курс на Остров Плена` : `${name(e.seat)} уходит от пиратов: за борт ${e.paid} марок топлива`;
    case 'escape':
      return `${name(e.seat)} бежит из плена ${e.way === 'N' ? 'на север' : 'на запад, к гроту Великого Лоцмана'}`;
    case 'tow':
      return `${name(e.seat)} берёт на буксир ${name(e.victim)} (+${e.marks} марки)`;
    case 'ice':
      return 'Лазурный океан у острова Благоразумия сковало льдами — дальше только Южным проливом';
    case 'end':
      return `<b>${e.result.text}</b>`;
    default:
      return null;
  }
}

const esc = (t: string) => t.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!);
