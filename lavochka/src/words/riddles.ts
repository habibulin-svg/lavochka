const cache = new Map<number, Riddle[]>();

/** Сложность по уровню бота: лёгкий спрашивает простое, сложный — трудное. */
export const diffForLevel = (level: number) => (Math.max(0, Math.min(2, Math.round(level) || 0)) + 1) as 1 | 2 | 3;

/** С какой удачей отвечает бот: лёгкий 30 %, средний 60 %, сложный 80 %. */
export const ANSWER_CHANCE = [30, 60, 80];

/** Загадки нужной сложности: база кроссвордов, а если она ещё не загружена — свой набор. */
export function riddlesOf(diff: number): Riddle[] {
  const d = Math.max(1, Math.min(3, Math.round(diff) || 1)) as 1 | 2 | 3;
  const base = allClues();
  if (base.length) {
    const hit = cache.get(d);
    if (hit) return hit;
    const list = base
      .filter((c) => c.diff === d && /^[а-яё]+$/i.test(c.word) && c.word.length >= 3 && c.word.length <= 14 && c.long.length >= 12)
      .map((c) => ({ q: c.long, a: c.word, diff: d }));
    if (list.length) {
      cache.set(d, list);
      return list;
    }
  }
  return OWN_RIDDLES.filter((r) => r.diff === d);
}

/** Случайная загадка нужной сложности. */
export function randomRiddle(diff: number, rng: { int(n: number): number }): Riddle {
  const list = riddlesOf(diff);
  const one = list[rng.int(Math.max(1, list.length))] ?? OWN_RIDDLES[0];
  return one;
}

/** Сверить ответ: строчными, «ё» → «е», без знаков и пробелов. */
export function sameAnswer(given: string, right: string): boolean {
  const norm = (s: string) =>
    s
      .toLowerCase()
      .replace(/ё/g, 'е')
      .replace(/[^a-zа-я0-9]/g, '');
  const g = norm(given ?? '');
  const r = norm(right ?? '');
  return !!r && g === r;
}

/** Ответы, которые считаем верными наравне с точным: «ветер» и «ветерок», «сон» и «сны». */
export function answerMatches(given: string, right: string): boolean {
  if (sameAnswer(given, right)) return true;
  const norm = (s: string) => s.toLowerCase().replace(/ё/g, 'е').replace(/[^a-zа-я0-9]/g, '');
  const g = norm(given ?? '');
  const r = norm(right ?? '');
  if (g.length < 4 || r.length < 4) return false;
  return g.startsWith(r) || r.startsWith(g);
}
