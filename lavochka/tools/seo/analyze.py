def norm(p):
    return p.lower().replace('ё', 'е')


def relevant(game, p):
    keys = GAME_KEYS.get(game)
    if not keys:
        return True
    words = p.split()
    for k in keys:
        if ' ' in k:
            if k in p:
                return True
        elif any(w.startswith(k) and (len(k) > 2 or w == k) for w in words):
            return True
    return False


def intent(p):
    for name, rx in INTENTS:
        if rx.search(p):
            return name
    return 'other'


def main():
    by_game = defaultdict(dict)  # game → phrase → count
    for f in os.listdir(RAW):
        if not f.endswith('.json'):
            continue
        d = json.load(open(os.path.join(RAW, f), encoding='utf-8'))
        g = d['game']
        for r in d.get('results', []):
            p = norm(r['phrase'])
            if STOP.search(p) or not relevant(g, p):
                continue
            by_game[g][p] = max(by_game[g].get(p, 0), int(r['count']))

    summary = []
    data = {}
    for g, ph in by_game.items():
        items = sorted(ph.items(), key=lambda x: -x[1])
        buckets = defaultdict(list)
        for p, c in items:
            buckets[intent(p)].append((p, c))
        head = items[0][1] if items else 0
        play = buckets['play'][0][1] if buckets['play'] else 0
        rules = buckets['rules'][0][1] if buckets['rules'] else 0
        dl = buckets['download'][0][1] if buckets['download'] else 0
        var = {}
        for v in VARIANTS.get(g, []):
            vp = [(p, c) for p, c in items if v in p]
            if vp:
                var[v] = {'top': vp[0], 'play': next(((p, c) for p, c in vp if intent(p) == 'play'), None)}
        data[g] = {
            'head': items[:1],
            'play': buckets['play'][:40],
            'rules': buckets['rules'][:15],
            'download': buckets['download'][:5],
            'other': buckets['other'][:15],
            'variants': var,
        }
        summary.append((g, head, play, rules, dl))

    os.makedirs(OUT, exist_ok=True)
    json.dump(data, open(os.path.join(OUT, 'games.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)

    md = ['# Спрос по играм (Wordstat, очищено)', '',
          'Числа — показы в месяц по головной фразе намерения (Wordstat считает фразу вместе со всеми её продолжениями).', '',
          '| Игра | Всего (головная) | Играть/онлайн | Правила | Скачать |', '|---|---|---|---|---|']
    for g, head, play, rules, dl in sorted(summary, key=lambda x: -x[2]):
        md.append(f'| {g} | {head:,} | {play:,} | {rules:,} | {dl:,} |'.replace(',', ' '))
    md += ['', '## По играм', '']
    for g, _, play, _, _ in sorted(summary, key=lambda x: -x[2]):
        d = data[g]
        md.append(f'### {g}')
        md.append('Играть: ' + '; '.join(f'{p} {c}' for p, c in d['play'][:15]))
        if d['rules']:
            md.append('Правила: ' + '; '.join(f'{p} {c}' for p, c in d['rules'][:6]))
        if d['variants']:
            md.append('Варианты: ' + '; '.join(
                f"{v}: {x['top'][0]} {x['top'][1]}" + (f" / {x['play'][0]} {x['play'][1]}" if x['play'] else '')
                for v, x in sorted(d['variants'].items(), key=lambda kv: -kv[1]['top'][1])))
        md.append('')
    open(os.path.join(OUT, 'analysis.md'), 'w', encoding='utf-8').write('\n'.join(md))
    print('готово:', len(data), 'игр')


if __name__ == '__main__':
    main()
