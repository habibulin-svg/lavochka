def norm(cid):
    """Идентификаторы в разметке писались то латиницей, то кириллицей (7a и 7а) — приводим к одному виду."""
    return str(cid).replace('a', 'а').replace('b', 'б')


def load(part):
    cells = json.load(open(os.path.join(SRC, 'cells-%d.json' % part), encoding='utf8'))
    path_file = os.path.join(SRC, 'path-%d.json' % part)
    if not os.path.exists(path_file):
        return cells, None
    return cells, json.load(open(path_file, encoding='utf8'))


def order(part):
    """Порядок клеток в собранном поле: главный путь, затем дороги развилок, затем свободные клетки."""
    ids = list(MAIN[part])
    for fid in BRANCHES.get(part, {}):
        for r in BRANCHES[part][fid]:
            ids += list(r['ids'])
            if r.get('exit'):
                ids.append(r['exit'])
    ids += list(LOOSE.get(part, []))
    out = []
    for cid in ids:
        c = norm(cid)
        if c not in out:
            out.append(c)
    return out


ORDER = {p: order(p) for p in PARTS}
IDX = {p: {cid: i for i, cid in enumerate(ORDER[p])} for p in PARTS}


def resolve(code, part):
    """Подставить номера клеток вместо «@id» (для field: — в поле-адресате)."""
    if code.startswith('field:'):
        _, mapid, target = code.split(':', 2)
        p = {v: k for k, v in MAP_OF.items()}[mapid]
        cid = norm(target.lstrip('@'))
        if cid not in IDX[p]:
            raise SystemExit('поле %d: переход в %s к «%s», а такой клетки там нет' % (part, mapid, cid))
        return 'field:%s:%d' % (mapid, IDX[p][cid])
    def sub(m):
        cid = norm(m.group(1))
        if cid not in IDX[part]:
            raise SystemExit('поле %d: ссылка на «%s», а такой клетки в поле нет' % (part, cid))
        return str(IDX[part][cid])
    return re.sub(r'@([\w\-а-яёА-ЯЁ]+)', sub, code)


def build(part=1):
    nodes, path = load(part)
    if not path:
        print('поле %d: путь не размечен (нет path-%d.json) — собирать нечего' % (part, part))
        return
    byid = {norm(c['id']): c for c in path['cells']}
    points = {norm(n['n']) for n in nodes.get('nodes', [])}
    table = {norm(k): v for k, v in SIGNS.get(part, {}).items()}
    extra = {norm(k): v for k, v in EXTRA_SIGNS.get(part, {}).items()}

    cells, idx = [], {}

    def put(cid, off=False):
        cid = norm(cid)
        if cid in idx:
            return idx[cid]
        src = byid.get(cid)
        if src is None:
            raise SystemExit('в path-%d.json нет клетки «%s»' % (part, cid))
        cell = {'x': round(src['x']), 'y': round(src['y'])}
        if cid in points:
            cell['l'] = cid
        if off:
            cell['off'] = 1
        cells.append(cell)
        idx[cid] = len(cells) - 1
        return idx[cid]

    main = [put(c) for c in MAIN[part]]
    end = main[-1]
    # дороги развилок — клетками после главного пути
    roads = {}
    for fid, list_ in BRANCHES.get(part, {}).items():
        roads[norm(fid)] = [{'road': r['road'], 'ids': [put(c, off=True) for c in r['ids']],
                             'exit': put(r['exit'], off=r['exit'] not in MAIN[part]) if r.get('exit') else None}
                            for r in list_]
    for cid in LOOSE.get(part, []):
        put(cid, off=True)
    for cid in extra:
        if cid not in idx:
            put(cid, off=True)
    # знаки пунктов
    for cid, i in list(idx.items()):
        code, text = table.get(cid, extra.get(cid, ('', '')))
        if not code:
            continue
        cell = cells[i]
        if code == 'fork':
            f = BYDIFF[part][cid]
            lists = [r['ids'] + ([r['exit']] if r['exit'] is not None else []) for r in roads[cid]]
            names = ';'.join(r['road'] for r in roads[cid])
            cell['s'] = 'fork:%s|%s|%s' % (''.join(str(x) for x in f), names,
                                           '|'.join(','.join(map(str, b)) for b in lists))
            cell['r'] = text
        elif code == 'pick':
            # загадка «угаданное число — номер пункта»: ответами идут номерные пункты поля
            opts = [c for c in MAIN[part] if norm(c) in points and norm(c) != 'старт']
            cell['s'] = 'pick:%s|%s|%s' % (text, ','.join(norm(c) for c in opts),
                                           ','.join(str(idx[norm(c)]) for c in opts))
            cell['r'] = 'угаданное число — номер пункта'
        else:
            cell['s'] = resolve(code, part)
            cell['r'] = text
    out = {'w': int(path['w']), 'h': int(path['h']), 'end': end, 'cells': cells}
    os.makedirs(OUT, exist_ok=True)
    name = os.path.join(OUT, '%s.json' % MAP_OF[part])
    with open(name, 'w', encoding='utf8') as f:
        json.dump(out, f, ensure_ascii=False, separators=(',', ':'))
    print('поле %d: %d клеток пути, %d на дорогах, знаков %d -> %s'
          % (part, end + 1, len(cells) - end - 1, sum(1 for c in cells if 's' in c), os.path.basename(name)))


def check(part):
    """Сверка: у каждого узла поля есть знак или пометка «обычный», у каждой развилки — таблица."""
    cells, path = load(part)
    table = SIGNS.get(part)
    if table is None:
        print('поле %d: знаки ещё не расписаны' % part)
        return
    used = set()
    for node in cells.get('nodes', []):
        n = norm(node['n'])
        if n in table:
            used.add(n)
            code, text = table[n]
            note = ''
            if code == 'fork':
                f = BYDIFF.get(part, {}).get(n)
                note = ' дороги: %s' % ', '.join(r['road'] for r in BRANCHES[part][n]) if f else ' !! нет таблицы BYDIFF'
            print('  %-10s %-14s %s%s' % (n, code, text, note))
        else:
            print('  %-10s %-14s %s' % (n, '—', 'знака нет (обычный пункт?)'))
    for n in table:
        if n not in used:
            print('  !! знак для «%s» есть в таблице, но такого узла нет на поле' % n)
    print('поле %d: путь по кружкам %s' % (part, 'есть' if path else 'НЕ размечен (path-%d.json)' % part))


