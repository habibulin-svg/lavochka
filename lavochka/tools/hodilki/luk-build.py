FIELDS = {1: F1, 2: F2, 3: F3}
try:
    from importlib import util as _u
    _spec = _u.spec_from_file_location('luk4spec', os.path.join(HERE, 'luk-build4.py'))
    _m = _u.module_from_spec(_spec)
    _spec.loader.exec_module(_m)
    FIELDS[4] = _m.F4
except FileNotFoundError:
    pass


def circles(n):
    return json.load(open(os.path.join(HERE, 'luk', 'circles-%d.json' % n), encoding='utf8'))


def layout(n):
    f = FIELDS[n]
    main = f['MAIN'].split()
    order = list(main)
    for e in f['EDGES']:
        for c in e.split():
            if c not in order:
                order.append(c)
    for name in list(f['SIGNS']):
        for ref in re.findall(r'@([^\s|,]+)', re.sub(r'field:luk\d:@[^\s|,]+', '', f['SIGNS'][name][0])):
            if ref not in order:
                order.append(ref)
    return main, order


def old(n):
    return json.load(open(os.path.join(OUT, 'luk%d.json' % n), encoding='utf8'))


def build_all():
    lay = {n: layout(n) for n in FIELDS}
    idx = {n: {c: i for i, c in enumerate(lay[n][1])} for n in FIELDS}
    # поле 4 пока в старой разметке: ссылки на него — по подписям его клеток, а его переходы
    # в части 1–3 пересчитываются ниже по подписям старых клеток
    keep4 = 4 not in FIELDS
    if keep4:
        idx[4] = {c['l']: i for i, c in reversed(list(enumerate(old(4)['cells']))) if c.get('l')}
        before = {n: old(n)['cells'] for n in (1, 2, 3)}
    for n, f in FIELDS.items():
        main, order = lay[n]
        circ = circles(n)
        end = len(main) - 1
        succ = {}
        for e in f['EDGES']:
            ch = e.split()
            for a, b in zip(ch, ch[1:]):
                if a in succ and succ[a] != b:
                    raise SystemExit('поле %d: у «%s» два продолжения: %s и %s' % (n, a, succ[a], b))
                succ[a] = b

        def ref(m):
            return str(idx[n][m.group(1)])

        def fref(m):
            return 'field:luk%s:%d' % (m.group(1), idx[int(m.group(1))][m.group(2)])

        cells = []
        for i, c in enumerate(order):
            if c in f['PTS']:
                x, y = f['PTS'][c]
            elif re.fullmatch(r'c\d+', c):
                p = circ[int(c[1:])]
                x, y = p['x'], p['y']
            else:
                raise SystemExit('поле %d: нет координат у «%s»' % (n, c))
            cell = {'x': int(x), 'y': int(y)}
            if c not in f['UNLABELED'] and not re.fullmatch(r'c\d+', c):
                cell['l'] = f['LABEL'].get(c, c)
            if i > end:
                cell['off'] = 1
            nx = succ.get(c)
            if nx is not None:
                j = idx[n][nx]
                if not (i < end and j == i + 1):
                    cell['n'] = j
            elif i < end:
                cell['n'] = -1
            if c in f.get('HOLD', {}):
                die, goal = f['HOLD'][c]
                cell['h'] = [die, idx[n][goal.lstrip('@')]]
            if c in f['SIGNS']:
                code, text = f['SIGNS'][c]
                code = re.sub(r'field:luk(\d):@([^\s|,]+)', fref, code)
                code = re.sub(r'@([^\s|,]+)', ref, code)
                cell['s'] = code
                cell['r'] = text
            cells.append(cell)
        w, h = SIZE[n]
        out = {'w': w, 'h': h, 'end': end, 'cells': cells}
        with open(os.path.join(OUT, 'luk%d.json' % n), 'w', encoding='utf8') as fh:
            json.dump(out, fh, ensure_ascii=False, separators=(',', ':'))
        print('luk%d: %d клеток, путь %d, знаков %d' % (n, len(cells), end + 1, sum('s' in c for c in cells)))
    if keep4:
        raw = old(4)

        def remap(m):
            label = before[int(m.group(1))][int(m.group(2))].get('l')
            if label not in idx[int(m.group(1))]:
                raise SystemExit('поле 4: переход на luk%s:%s («%s») — такой клетки больше нет' % (m.group(1), m.group(2), label))
            return 'field:luk%s:%d' % (m.group(1), idx[int(m.group(1))][label])
        for c in raw['cells']:
            if 's' in c:
                c['s'] = re.sub(r'field:luk([123]):(\d+)', remap, c['s'])
        with open(os.path.join(OUT, 'luk4.json'), 'w', encoding='utf8') as fh:
            json.dump(raw, fh, ensure_ascii=False, separators=(',', ':'))
        print('luk4: старая разметка, переходы пересчитаны')


if __name__ == '__main__':
    build_all()
